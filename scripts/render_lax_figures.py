#!/usr/bin/env python3
"""Render the ``CASE-LAX-DG`` figures from a committed record (headless nodes).

The pool driver renders its figures inline, which makes the *record* hostage to
the plotting stack: the loong64 compute nodes carry ``numpy``/``torch`` but no
``matplotlib``, so ``python -m benchmarks.lax_case_pool`` died at
``render_figures`` *after* 22 min of solver time and wrote no ``metrics.json``
at all.  This script decouples the two: the cluster run writes the numbers
(``--skip-figures``), and the figures are rendered here from the record plus
``profiles.npz`` -- the same arrays the driver would have plotted.

Every input is read back from the artifact, so the figures cannot show a run
other than the one in ``metrics.json``.  That used to be a sentence; it is now a
check.  Each render writes ``figures_binding.json`` next to the record, which
ties the two directions together::

    record_sha256, profiles_sha256, renderer_sha256   (what the figures came from)
    figures_sha256: {name: sha256}                   (what came out)

That binding can fail in ways a digest stored *inside* the record cannot: if the
record is regenerated by a new run and the figures are never re-rendered, the
record's own copy of a digest would still look self-consistent, while the
sidecar's ``record_sha256`` goes stale and the gate says FAIL.
``tests/test_lax_figure_reproducibility.py`` holds the gates: record/disk/digest
three-way agreement (no matplotlib needed), a one-byte tamper control, a record
tamper control, and a byte-identical re-render.

Re-rendering is idempotent: the record is written back in *its own* existing
JSON style, so a no-op render produces no diff.  (Before this, the writer
hard-coded ``indent=1`` while the pool record is ``indent=2``, so every re-run
rewrote 2 518 lines of numbers that had not changed, so a render that changed
nothing was indistinguishable in the diff from a full regeneration.)::

    python scripts/render_lax_figures.py            # pool + limiter arms
    python scripts/render_lax_figures.py --pool     # only the pool record
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from benchmarks.lax_case_pool import (  # noqa: E402
    OUT as POOL_OUT, render_acceptance_figure, render_figures,
    render_time_figure,
)
from benchmarks.lax_case_pool_limiter_arms import OUT as ARMS_OUT  # noqa: E402
from benchmarks.lax_case_pool_limiter_arms import render_figures as render_arms  # noqa: E402

FIELDS = ("density", "velocity", "pressure")
RENDERER = Path("scripts/render_lax_figures.py")
PROVENANCE = ("scripts/render_lax_figures.py (record + profiles.npz; "
              "rendered off-node: the loong64 compute image has no matplotlib)")
RECORDS = ((POOL_OUT, "pool"), (ARMS_OUT, "arms"))
BINDING = "figures_binding.json"


def _as_list(value):
    """``render_*_figure`` helpers return either one ``Path`` or a list."""
    return list(value) if isinstance(value, (list, tuple)) else [value]


def _names(files):
    return sorted({Path(p).name for p in files})


def sha256_file(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def renderer_path(root=ROOT):
    """The renderer under ``root`` when rendering a mirror, else this checkout."""
    candidate = Path(root) / RENDERER
    return candidate if candidate.is_file() else ROOT / RENDERER


def rel(path, root=ROOT):
    """Repo-relative posix path (stable across checkouts)."""
    return Path(path).resolve().relative_to(Path(root).resolve()).as_posix()


def figure_digests(fig_dir, names):
    """``{name: sha256}`` for the rendered files, refusing a missing one."""
    out = {}
    for name in names:
        path = Path(fig_dir) / name
        if not path.is_file():
            raise FileNotFoundError(f"figure {path} was not written")
        out[name] = sha256_file(path)
    return out


def write_binding(rec_dir, root=ROOT):
    """Write ``figures_binding.json``: inputs -> rendered bytes, one sidecar."""
    rec_dir = Path(rec_dir)
    metrics_path = rec_dir / "metrics.json"
    metrics = json.loads(metrics_path.read_text())
    names = list(metrics.get("figures") or [])
    binding = {
        "record": rel(metrics_path, root),
        "record_sha256": sha256_file(metrics_path),
        "profiles": rel(rec_dir / "profiles.npz", root),
        "profiles_sha256": sha256_file(rec_dir / "profiles.npz"),
        "renderer": RENDERER.as_posix(),
        "renderer_sha256": sha256_file(renderer_path(root)),
        "figures_provenance": metrics.get("figures_provenance"),
        "figures": names,
        "figures_sha256": figure_digests(rec_dir / "figures", names),
    }
    (rec_dir / BINDING).write_text(json.dumps(binding, indent=2) + "\n")
    return binding


def check_binding(rec_dir, root=ROOT):
    """Compare a record's figures against its ``figures_binding.json``.

    Cheap, matplotlib-free staleness gate: returns ``(ok, rows)`` where a row is
    ``(what, recorded, actual)``.  A missing sidecar, a record that no longer
    matches ``record_sha256`` (a new run whose figures were never re-rendered),
    or a figure whose bytes moved all read as FAIL -- never as "skip".
    """
    rec_dir = Path(rec_dir)
    record_path = rec_dir / "metrics.json"
    binding_path = rec_dir / BINDING
    if not record_path.is_file():
        return False, [("metrics.json", "present", "missing")]
    if not binding_path.is_file():
        return False, [("figures_binding.json", "present", "missing")]
    binding = json.loads(binding_path.read_text())
    metrics = json.loads(record_path.read_text())

    figures = list(metrics.get("figures") or [])
    rows, ok = [], bool(figures)
    want = binding.get("figures_sha256") or {}

    rows.append(("record_sha256", binding.get("record_sha256"),
                 sha256_file(record_path)))
    profiles = rec_dir / "profiles.npz"
    rows.append(("profiles_sha256", binding.get("profiles_sha256"),
                 sha256_file(profiles) if profiles.is_file() else None))
    rows.append(("renderer_sha256", binding.get("renderer_sha256"),
                 sha256_file(renderer_path(root))))
    for what, recorded, actual in rows:
        if not actual or actual != recorded:
            ok = False

    if sorted(binding.get("figures") or []) != sorted(figures):
        ok = False
        rows.append(("figures list", ",".join(binding.get("figures") or []),
                     ",".join(figures)))
    if sorted(want) != sorted(figures):
        ok = False
        rows.append(("digest keys", ",".join(sorted(want)),
                     ",".join(sorted(figures))))
    for name in figures:
        path = rec_dir / "figures" / name
        actual = sha256_file(path) if path.is_file() else None
        rows.append((f"figures/{name}", want.get(name), actual))
        if not actual or actual != want.get(name):
            ok = False
    on_disk = sorted(p.name for p in (rec_dir / "figures").glob("*.png"))
    if on_disk != sorted(figures):          # orphan image or missing figure
        ok = False
        rows.append(("on-disk set", ",".join(figures), ",".join(on_disk)))
    return ok, rows


def write_record(path, metrics):
    """Re-serialise ``metrics`` in the record's own style (idempotent)."""
    path = Path(path)
    raw = path.read_text()
    indent = 2 if raw.startswith('{\n  "') else 1
    text = json.dumps(metrics, indent=indent)
    if raw.endswith("\n"):
        text += "\n"
    path.write_text(text)


def render_pool(root=ROOT):
    root = Path(root)
    rec_dir = root / POOL_OUT
    metrics = json.loads((rec_dir / "metrics.json").read_text())
    npz = np.load(rec_dir / "profiles.npz")
    profiles = {"points": npz["points"],
                "numerical": {f: npz[f"numerical_{f}"] for f in FIELDS},
                "exact": {f: npz[f"exact_{f}"] for f in FIELDS}}
    ladder = metrics["ladder"]
    # ``render_figures`` only needs the finest leg's identity for the title
    finest = {"cells": ladder[-1]["cells"], "degree": ladder[-1]["degree"]}
    fig_dir = rec_dir / "figures"
    # JSON stringifies the integer cell counts that double as dict keys
    entropy = [dict(e, relative_l1={int(k): v
                                    for k, v in e["relative_l1"].items()})
               for e in metrics["entropy_wave"]]
    files = _as_list(render_figures(metrics["waves"], ladder, finest, profiles,
                                    entropy, fig_dir))
    if metrics.get("time_refinement"):
        files.extend(_as_list(render_time_figure(metrics["time_refinement"], fig_dir)))
    files.extend(_as_list(render_acceptance_figure(ladder, metrics["acceptance"], fig_dir)))
    metrics["figures"] = _names(files)
    metrics["figures_provenance"] = PROVENANCE
    write_record(rec_dir / "metrics.json", metrics)
    write_binding(rec_dir, root)
    return metrics["figures"]


def render_arms_record(root=ROOT):
    root = Path(root)
    rec_dir = root / ARMS_OUT
    metrics = json.loads((rec_dir / "metrics.json").read_text())
    npz = np.load(rec_dir / "profiles.npz")
    arm_results, profiles = {}, {}
    from benchmarks.lax_case_pool import exact_waves  # record drops "waves"
    for arm, record in metrics["arms"].items():
        arm_results[arm] = dict(record, waves=exact_waves())
        profiles[arm] = {
            "points": npz[f"{arm}_points"],
            "numerical": {f: npz[f"{arm}_numerical_{f}"] for f in FIELDS},
            "exact": {f: npz[f"{arm}_exact_{f}"] for f in FIELDS},
        }
    files = render_arms(arm_results, profiles, rec_dir / "figures")
    metrics["figures"] = _names(files)
    metrics["figures_provenance"] = PROVENANCE
    write_record(rec_dir / "metrics.json", metrics)
    write_binding(rec_dir, root)
    return metrics["figures"]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pool", action="store_true", help="pool record only")
    parser.add_argument("--arms", action="store_true", help="limiter arms only")
    args = parser.parse_args(argv)
    which = [("pool", render_pool), ("arms", render_arms_record)]
    if args.pool or args.arms:
        which = [(n, f) for n, f in which if (args.pool and n == "pool")
                 or (args.arms and n == "arms")]
    for name, fn in which:
        try:
            print(f"[figures] {name}: {fn()}")
        except Exception as exc:  # a missing figure must not hide the numbers
            print(f"[figures] {name}: FAILED {type(exc).__name__}: {exc}",
                  file=sys.stderr)


if __name__ == "__main__":
    main()
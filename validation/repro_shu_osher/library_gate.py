"""Library-side acceptance entry of the Shu--Osher case: run it and record it.

The case owner is ``tensordg.cases.shock_entropy``; this script only *drives* its
public entry (``gate_report``) and writes the numbers down, so that the documented

    python -m tensordg.cases.shock_entropy --ncells 400 --degree 2 \
           --reference benchmarks/data/shu_osher_reference.npz

is backed by a machine-generated record instead of a hand-copied table.

Two things are recorded per configuration:

* the acceptance report itself (anchors, mass budget, shock position, and - when a
  reference is given - the relative L1 with the grid pair that was actually
  compared);
* a **baseline/control pair for the shock locator**: the pre-fix locator (nearest
  cell, hard-coded level 2.0, taken verbatim from the code it replaces) next to the
  shipped one (interpolated crossing at the mid-level between plateau and
  pre-shock density).  Both see the *same* profile, so the difference is the
  locator alone, not the solution.

Output: ``docs/shu_osher_library_gate.md`` (git-tracked; ``runs/`` and
``artifacts/`` are filtered out of agent branches, ``docs/`` is not).

Usage::

    python validation/repro_shu_osher/library_gate.py            # 48/1, 100/2, 400/2
    python validation/repro_shu_osher/library_gate.py --configs 100/2
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

if __package__ in (None, ""):  # allow running as a plain path
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tensordg.cases.shock_entropy import (  # noqa: E402
    DOMAIN,
    PLATEAU_MARGIN,
    SHOCK_LEVEL,
    UNDISTURBED_MARGIN,
    gate_report,
    rankine_hugoniot_anchor,
    shock_position,
)

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / "benchmarks" / "data" / "shu_osher_reference.npz"
OUT = ROOT / "docs" / "shu_osher_library_gate.md"
TOLERANCE_PERCENT = 5.0


def legacy_shock_position(x, rho):
    """Baseline: the pre-fix locator (nearest cell, literally level ``2.0``).

    Copied from the code this change replaces, so the comparison in the record is
    against the real previous behaviour and not against a straw man.
    """
    level = 2.0
    for i in range(rho.size - 1, 0, -1):
        if rho[i - 1] > level >= rho[i]:
            return float(x[i])
    return None


def load_reference():
    if not REFERENCE.exists():  # pragma: no cover
        return None, None
    blob = np.load(REFERENCE, allow_pickle=True)
    meta = json.loads(str(blob["meta"])) if "meta" in blob.files else None
    return (blob["x"], blob["rho"]), meta


def run_config(ncells: int, degree: int, reference, reference_meta) -> dict:
    start = time.perf_counter()
    report = gate_report(ncells, degree=degree, limiter="weno", cfl=0.4,
                         reference=reference, tolerance_percent=TOLERANCE_PERCENT,
                         reference_meta=reference_meta, include_profile=True)
    report["wall_time_s"] = time.perf_counter() - start

    # the locator baseline/control reads the *same* solved profile (one solve per
    # configuration): the only difference between the two columns is the locator.
    profile = report.pop("profile")
    x, rho = np.asarray(profile["x"]), np.asarray(profile["rho"])
    exact = rankine_hugoniot_anchor()["shock_position_analytic"]
    legacy = legacy_shock_position(x, rho)
    shipped = shock_position(x, rho)
    dx = (DOMAIN[1] - DOMAIN[0]) / rho.size
    report["shock_locator"] = {
        "analytic_position": exact,
        "cell_step": dx,
        "legacy": {"level": 2.0, "nearest_cell": legacy,
                   "abs_error_percent": None if legacy is None
                   else 100.0 * abs(legacy - exact) / exact},
        "shipped": {"level": SHOCK_LEVEL, "interpolated": shipped,
                    "abs_error_percent": None if shipped is None
                    else 100.0 * abs(shipped - exact) / exact},
        "shipped_beats_legacy": bool(
            legacy is not None and shipped is not None
            and abs(shipped - exact) < abs(legacy - exact)),
    }
    return report


def render(configs) -> str:
    anchor = rankine_hugoniot_anchor()
    lines = [
        "# Shu--Osher case: library acceptance record (generated)",
        "",
        "> Generated by `python validation/repro_shu_osher/library_gate.py`.",
        "> Every number below is written by the script from the run - none is typed by hand.",
        "",
        "Case: `shu-osher-1988-shock-entropy` (Mach-3 shock at `x = -4` sweeping a",
        "`rho = 1 + 0.2 sin(5x)` density wave in a `gamma = 1.4` gas, `t = 1.8`).",
        "Owner: `tensordg/cases/shock_entropy.py`.",
        "",
        "## Why this file exists",
        "",
        "`gate_report` is the library-side acceptance entry, and its documented command",
        "compares a DG run against `benchmarks/data/shu_osher_reference.npz`. That file is a",
        "*300-cell DG P3* profile, so a 400-cell candidate has no integer refinement ratio",
        "against it: before this record the documented command died with",
        "`ValueError: profile shapes differ: (400,) vs (300,)`. The comparison now",
        "conservatively re-averages both profiles onto the coarser grid and echoes the grid",
        "pair under `reference.comparison`, so the command reports a number and the number",
        "says what it compared.",
        "",
        "## Closed-form skeleton used by every measurement window",
        "",
        "| quantity | value |",
        "|---|---|",
        f"| analytic shock position at t=1.8 | {anchor['shock_position_analytic']:.6f} |",
        f"| analytic contact position | {anchor['contact_position_analytic']:.6f} |",
        f"| quiet-zone head | {anchor['quiet_zone_head_analytic']:.6f} |",
        f"| post-shock plateau window | [{DOMAIN[0]:.3f}, "
        f"{anchor['post_shock_plateau']['window'][1]:.3f}] (`DIAPHRAGM + {PLATEAU_MARGIN}`) |",
        f"| undisturbed window | [{anchor['undisturbed_window'][0]:.6f}, "
        f"{anchor['undisturbed_window'][1]:.3f}] (`shock + {UNDISTURBED_MARGIN}`) |",
        f"| shock-detection level | {SHOCK_LEVEL:.6f} (mid-level plateau/pre-shock) |",
        "",
        "## Configurations",
        "",
        "| N | P | steps | plateau dev % | undisturbed sine L1 % | mass err % of M0 "
        "| shock x | shock err % | vs reference L1 % | comparison | gate (5%) |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in configs:
        ref = r.get("reference") or {}
        comp = (ref.get("comparison") or {})
        l1 = r.get("rel_l1_percent")
        lines.append(
            f"| {r['configuration']['ncells']} | {r['configuration']['degree']} | {r['steps']} "
            f"| {r['plateau_dev_percent']:.2e} "
            f"| {r['preshock_sine_rel_l1_percent']:.4f} "
            f"| {r['mass_error_percent_of_initial']:.2e} "
            f"| {r['shock_position']:.6f} "
            f"| {r.get('shock_position_percent_error', float('nan')):.4f} "
            f"| {'n/a' if l1 is None else f'{l1:.4f}'} "
            f"| {comp.get('method', 'n/a')} "
            f"({comp.get('candidate_cells', '?')} vs {comp.get('reference_cells', '?')}"
            f" → {comp.get('common_grid_cells', '?')}) "
            f"| {'PASS' if r.get('passes_gate') else 'n/a' if r.get('passes_gate') is None else 'FAIL'} |"
        )
    lines += [
        "",
        "## Shock-locator baseline vs shipped (same profile, locator is the only change)",
        "",
        "| N | P | cell step | legacy (nearest cell, level 2.0) | error % "
        "| shipped (interpolated, mid-level) | error % | shipped beats legacy |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in configs:
        loc = r["shock_locator"]
        lines.append(
            f"| {r['configuration']['ncells']} | {r['configuration']['degree']} "
            f"| {loc['cell_step']:.4f} | {loc['legacy']['nearest_cell']:.5f} "
            f"| {loc['legacy']['abs_error_percent']:.4f} "
            f"| {loc['shipped']['interpolated']:.5f} "
            f"| {loc['shipped']['abs_error_percent']:.4f} "
            f"| {'yes' if loc['shipped_beats_legacy'] else 'no'} |"
        )
    lines += [
        "",
        "## Raw reports",
        "",
        "```json",
        json.dumps(configs, indent=1),
        "```",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--configs", nargs="*", default=["48/1", "100/2", "400/2"],
                    help="N/degree pairs, e.g. 400/2")
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--json-out", default=str(OUT.with_suffix(".json")),
                    help="machine-readable copy of the same records")
    args = ap.parse_args(argv)

    reference, reference_meta = load_reference()
    configs = []
    for item in args.configs:
        ncells, degree = (int(part) for part in item.split("/"))
        t0 = time.perf_counter()
        configs.append(run_config(ncells, degree, reference, reference_meta))
        print(f"{item}: {time.perf_counter() - t0:.1f}s "
              f"rel_L1={configs[-1].get('rel_l1_percent')}", flush=True)

    text = render(configs)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text + "\n")
    print(f"wrote {out}")
    # the record the figure script and any downstream check read: no hand copying
    Path(args.json_out).write_text(json.dumps({"configs": configs,
                                               "anchor": rankine_hugoniot_anchor()},
                                              indent=1) + "\n")
    print(f"wrote {args.json_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
def primitive_from_conserved(state: np.ndarray, gamma: float = GAMMA):
    """``(rho, u, v, p)`` from conservative ``(rho, rho u, rho v, E)``."""
    rho = np.maximum(state[..., 0], 1e-12)
    velocity_x = state[..., 1] / rho
    velocity_y = state[..., 2] / rho
    pressure = (gamma - 1.0) * (
        state[..., 3] - 0.5 * rho * (velocity_x ** 2 + velocity_y ** 2)
    )
    return rho, velocity_x, velocity_y, pressure


def conserved_from_primitive(rho, velocity_x, velocity_y, pressure,
                             gamma: float = GAMMA) -> np.ndarray:
    """Conservative vector ``(rho, rho u, rho v, E)`` stacked on the last axis."""
    energy = pressure / (gamma - 1.0) + 0.5 * rho * (
        velocity_x ** 2 + velocity_y ** 2
    )
    return np.stack([rho, rho * velocity_x, rho * velocity_y, energy], axis=-1)


def euler_flux(state: np.ndarray, gamma: float = GAMMA):
    """Physical fluxes ``(F_x, F_y)`` of the 2-D Euler equations."""
    rho, velocity_x, velocity_y, pressure = primitive_from_conserved(state, gamma)
    energy = state[..., 3]
    flux_x = np.stack(
        [
            state[..., 1],
            state[..., 1] * velocity_x + pressure,
            state[..., 1] * velocity_y,
            velocity_x * (energy + pressure),
        ],
        axis=-1,
    )
    flux_y = np.stack(
        [
            state[..., 2],
            state[..., 2] * velocity_x,
            state[..., 2] * velocity_y + pressure,
            velocity_y * (energy + pressure),
        ],
        axis=-1,
    )
    return flux_x, flux_y


def hllc_normal(left: np.ndarray, right: np.ndarray, normal_x, normal_y,
                gamma: float = GAMMA) -> np.ndarray:
    """HLLC flux ``F_hat . n`` for an arbitrary **unit** normal ``(nx, ny)``.

    ``normal_x``/``normal_y`` broadcast against ``left[..., 0]``.  The result is
    the physical flux dotted with the unit normal, i.e. a flux per unit face
    length.  Degenerate (acoustically coincident) data falls back to Rusanov,
    exactly like ``euler_dg_2d._hllc``.
    """
    normal_x = np.asarray(normal_x, dtype=float)
    normal_y = np.asarray(normal_y, dtype=float)
    rho_l = np.maximum(left[..., 0], 1e-12)
    rho_r = np.maximum(right[..., 0], 1e-12)
    vel_lx, vel_ly = left[..., 1] / rho_l, left[..., 2] / rho_l
    vel_rx, vel_ry = right[..., 1] / rho_r, right[..., 2] / rho_r
    pres_l = np.maximum(
        (gamma - 1.0) * (left[..., 3] - 0.5 * rho_l * (vel_lx ** 2 + vel_ly ** 2)),
        1e-12,
    )
    pres_r = np.maximum(
        (gamma - 1.0) * (right[..., 3] - 0.5 * rho_r * (vel_rx ** 2 + vel_ry ** 2)),
        1e-12,
    )
    sound_l = np.sqrt(gamma * pres_l / rho_l)
    sound_r = np.sqrt(gamma * pres_r / rho_r)
    un_l = vel_lx * normal_x + vel_ly * normal_y
    un_r = vel_rx * normal_x + vel_ry * normal_y
    speed_l = np.minimum(un_l - sound_l, un_r - sound_r)
    speed_r = np.maximum(un_l + sound_l, un_r + sound_r)
    denominator = rho_l * (speed_l - un_l) - rho_r * (speed_r - un_r)
    safe = np.where(np.abs(denominator) < 1e-30, 1e-30, denominator)
    speed_m = (
        pres_r - pres_l
        + rho_l * un_l * (speed_l - un_l)
        - rho_r * un_r * (speed_r - un_r)
    ) / safe

    flux_lx, flux_ly = euler_flux(left, gamma)
    flux_rx, flux_ry = euler_flux(right, gamma)
    flux_l = flux_lx * normal_x[..., None] + flux_ly * normal_y[..., None]
    flux_r = flux_rx * normal_x[..., None] + flux_ry * normal_y[..., None]

    def star(state, rho, un, pres, speed, tangential):
        gap = speed - un
        gap = np.where(
            np.abs(gap) < 1e-14, np.where(gap < 0.0, -1e-14, 1e-14), gap
        )
        rho_star = rho * (speed - un) / (speed - speed_m)
        energy_star = rho_star * (
            state[..., 3] / rho
            + (speed_m - un) * (speed_m + pres / (rho * gap))
        )
        momentum_normal = rho_star * speed_m
        momentum_tangential = rho_star * tangential
        return np.stack(
            [
                rho_star,
                momentum_normal * normal_x - momentum_tangential * normal_y,
                momentum_normal * normal_y + momentum_tangential * normal_x,
                energy_star,
            ],
            axis=-1,
        )

    star_l = star(
        left, rho_l, un_l, pres_l, speed_l, -vel_lx * normal_y + vel_ly * normal_x
    )
    star_r = star(
        right, rho_r, un_r, pres_r, speed_r, -vel_rx * normal_y + vel_ry * normal_x
    )
    star_flux_l = flux_l + speed_l[..., None] * (star_l - left)
    star_flux_r = flux_r + speed_r[..., None] * (star_r - right)

    flux = np.where((speed_l >= 0.0)[..., None], flux_l, star_flux_l)
    flux = np.where((speed_m < 0.0)[..., None], star_flux_r, flux)
    flux = np.where((speed_r <= 0.0)[..., None], flux_r, flux)

    alpha = np.maximum(np.abs(un_l) + sound_l, np.abs(un_r) + sound_r)
    rusanov = 0.5 * (flux_l + flux_r) - 0.5 * alpha[..., None] * (right - left)
    degenerate = np.abs(speed_r - speed_l) < 1e-13
    return np.where(degenerate[..., None], rusanov, flux)


def wall_normal_flux(inner: np.ndarray, normal_x, normal_y,
                     gamma: float = GAMMA) -> np.ndarray:
    """Slip-wall numerical normal flux via the mirror ghost state + HLLC.

    ``inner`` are the *interior* traces ``(..., 4)`` on the wall face and
    ``(normal_x, normal_y)`` the unit face normal in the orientation the DG face
    term uses (``J grad(xi)`` / ``J grad(eta)``).  The ghost state mirrors the
    normal velocity and keeps density, pressure and the tangential velocity:

        ``rho_g = rho``, ``p_g = p``, ``u_n,g = -u_n``, ``u_t,g = u_t``.

    Because the Riemann fan is exactly symmetric, the star normal velocity is
    zero and the flux through the wall is ``(0, p, 0, 0)`` * up to round-off --
    i.e. impermeable and adiabatic -- but, unlike the bare ``(0, p n)`` flux, it
    inherits the HLLC dissipation that the interior faces have.  Dropping that
    dissipation is linearly unstable on a curved wall (observed: round-off grows
    ~6x per 10 RK steps until blow-up), so the ghost form is the one used.
    """
    state = np.asarray(inner, float)
    rho, velocity_x, velocity_y, pressure = primitive_from_conserved(state, gamma)
    normal_x = np.asarray(normal_x, float)
    normal_y = np.asarray(normal_y, float)
    normal_velocity = velocity_x * normal_x + velocity_y * normal_y
    tangential = -velocity_x * normal_y + velocity_y * normal_x
    ghost = conserved_from_primitive(
        rho,
        -normal_velocity * normal_x - tangential * normal_y,
        -normal_velocity * normal_y + tangential * normal_x,
        pressure,
        gamma,
    )
    return hllc_normal(state, ghost, normal_x, normal_y, gamma)


BOUNDARY_KINDS = ("auto", "periodic", "wall", "farfield", "outflow")


def cylinder_annulus_mesh(nr: int, ntheta: int, r_inner: float, r_outer: float,
                          degree: int = 1, growth: float = 1.0,
                          inner_curve=None):
    """Body-fitted polar O-grid around a circular cylinder, radially clustered.

    Axis 0 is radial (``axis0_lo`` = the cylinder wall, ``axis0_hi`` = the outer
    far-field circle), axis 1 is azimuthal and **periodic**; the wall flags mark
    the two circular boundaries.  ``growth >= 1`` is a geometric radial spacing
    with first-cell thickness

        ``dr0 = (r_outer - r_inner) (growth - 1) / (growth**nr - 1)``

    so ``growth = 1`` recovers the uniform spacing of
    ``curved_geometry.annulus_mesh``.  ``inner_curve(theta) -> (x, y)`` allows a
    non-circular body (CAD contract); the default is the exact circle.
    """
    nr, ntheta = int(nr), int(ntheta)
    if nr < 1 or ntheta < 4:
        raise ValueError("need nr >= 1 and ntheta >= 4")
    if not (0.0 < r_inner < r_outer):
        raise ValueError("require 0 < r_inner < r_outer")
    if growth < 1.0:
        raise ValueError("growth must be >= 1")
    nodes, _ = gll_nodes_weights(max(int(degree), 1))
    if abs(growth - 1.0) < 1e-14:
        radii = np.linspace(r_inner, r_outer, nr + 1)
    else:
        q = float(growth)
        dr0 = (r_outer - r_inner) * (q - 1.0) / (q ** nr - 1.0)
        radii = r_inner + dr0 * (q ** np.arange(nr + 1) - 1.0) / (q - 1.0)
        radii[-1] = r_outer
    if inner_curve is None:
        def inner_curve(theta):
            return np.stack([r_inner * np.cos(theta), r_inner * np.sin(theta)], -1)
    outer_curve = lambda theta: np.stack(
        [r_outer * np.cos(theta), r_outer * np.sin(theta)], -1)
    maps = []
    for i in range(nr):
        r_local = radii[i] + 0.5 * (radii[i + 1] - radii[i]) * (nodes + 1.0)
        lam_local = (r_local - r_inner) / (r_outer - r_inner)
        row = []
        for j in range(ntheta):
            theta_local = 2.0 * np.pi * (j + 0.5 * (nodes + 1.0)) / ntheta
            R, TH = np.meshgrid(r_local, theta_local, indexing="ij")
            lam = np.meshgrid(lam_local, theta_local, indexing="ij")[0]
            Pi, Po = inner_curve(TH), outer_curve(TH)
            X = (1.0 - lam) * Pi[..., 0] + lam * Po[..., 0]
            Y = (1.0 - lam) * Pi[..., 1] + lam * Po[..., 1]
            row.append(IsoparametricMap.from_nodal(X, Y))
        maps.append(row)
    return CurvedMesh(maps, periodic=(False, True), walls=(True, False, False, False))



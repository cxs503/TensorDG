"""Temporal-order probe: P3 isentropic vortex EOC under SSP-RK3 vs classical RK4.

Reads nothing from disk; every number printed here is generated by the solver
in this run (zero hand-copied values).
"""
from __future__ import annotations

import json

import numpy as np

from tensordg.euler_dg_2d import solve_euler_dg_2d_vortex, cell_fields
from tensordg.euler_2d import vortex_error

RES = [4, 8, 16]


def run(integrator: str, degree: int, res=RES, cfl: float = 0.15):
    errors = []
    for n in res:
        x, y, coeff, meta = solve_euler_dg_2d_vortex(
            ncells=n, degree=degree, final_time=0.05, cfl=cfl,
            strength=1.0, limiter=None, initial_projection="l2",
            time_integrator=integrator,
        )
        fields = cell_fields(coeff)
        errs = vortex_error(x, y, fields["conservative"], 0.05, 1.0)
        errors.append(errs["density"]["relative_l2"])
    h = [10.0 / n for n in res]
    eoc = [float(np.log(errors[i] / errors[i + 1]) / np.log(h[i] / h[i + 1]))
           for i in range(len(errors) - 1)]
    return {"integrator": integrator, "degree": degree, "res": list(res),
            "relative_l2": errors, "pairwise_eoc": eoc,
            "mean_eoc": float(np.mean(eoc))}


if __name__ == "__main__":
    out = []
    for integrator in ("rk3", "rk4"):
        for degree in (3,):
            out.append(run(integrator, degree))
    print(json.dumps(out, indent=2))
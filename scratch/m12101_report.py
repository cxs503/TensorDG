def fig_baseline(bc: dict, curved: list) -> tuple[bytes, str]:
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    for degree, marker in ((1, "o"), (2, "s")):
        for wb, colour, label in ((False, "#c0392b", "default (cell-const slope)"),
                                  (True, "#1f77b4", "well balanced")):
            xs, ys = [], []
            for rec in curved:
                if rec["degree"] == degree and rec["well_balanced"] is wb:
                    xs.append(rec["nx"])
                    ys.append(max(rec["u_max"], 1e-18))
            ax.loglog(xs, ys, marker=marker, color=colour, ls="-" if wb else "--",
                      label=f"P{degree} {label}")
    ax.axhline(1e-8, color="grey", lw=0.8, ls=":")
    ax.text(8.2, 1.4e-8, "pass criterion 1e-8 m/s", fontsize=7, color="grey")
    ax.set_xlabel("cells in x (ny = 4)")
    ax.set_ylabel(r"max spurious $|u|$ after t = 0.1 s  [m/s]")
    ax.set_title("Lake at rest on the quadratic bed $z_b=0.2x+0.05x^2$")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=7, loc="center right")
    fig.tight_layout()
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=150)
    plt.close(fig)
    caption = (f"Spurious current vs resolution. The default path saturates at "
               f"{bc['max_u_max_default_path']:.2e} m/s (P2) whatever the mesh; the "
               f"well-balanced path holds at {bc['max_u_max_well_balanced']:.2e} m/s.")
    return buf.getvalue(), caption


def fig_field() -> tuple[bytes, str]:
    nx, ny, degree, final_time = 16, 6, 2, 0.1
    h = lambda xx, yy: ETA0 - quadratic_bed(xx, yy)  # noqa: E731
    panels = []
    for wb in (False, True):
        x, y, coeff, _, meta = solve_swe_2d(
            h, zeros, zeros, quadratic_bed, nx=nx, ny=ny, degree=degree,
            final_time=final_time, domain=DOMAIN, cfl=0.3, well_balanced=wb)
        zb_avg = meta["zb_modes"][:, :, 0, 0] if meta["zb_modes"] is not None else (
            0.2 * x[:, None] + 0.05 * (x[:, None] ** 2 + (1.0 / nx) ** 2 / 12.0))
        eta = coeff[:, :, 0, 0, 0] + zb_avg
        panels.append((eta - ETA0, meta["steps"]))

    fig, axes = plt.subplots(1, 2, figsize=(11, 3.9), constrained_layout=True)
    vmax = max(float(p[0].abs().max()) for p in panels)
    for ax, (dev, steps), wb in zip(axes, panels, (False, True)):
        lim = vmax if not wb else vmax
        im = ax.pcolormesh(x.numpy(), y.numpy(), dev.numpy().T, cmap="RdBu_r",
                           vmin=-lim, vmax=lim, shading="nearest")
        ax.set_title(("default path" if not wb else "well balanced")
                     + f"  (P2, {nx}x{ny}, {steps} steps)", fontsize=9)
        ax.set_xlabel("x")
        ax.set_ylabel("y")
        fig.colorbar(im, ax=ax, label=r"$\eta-\eta_0$ [m]")
    fig.suptitle(r"Free-surface drift in a still lake, $t$ = 0.1 s, colour scale "
                 f"$\\pm${vmax:.1e} m (shared)", fontsize=9)
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=150)
    plt.close(fig)
    caption = ("Same colour scale in both panels: the default path develops an "
               f"O({vmax:.1e} m) free-surface pattern out of a still lake; the "
               "well-balanced path is flat at round-off.")
    return buf.getvalue(), caption


def fig_bed_jump() -> tuple[bytes, str]:
    nx, ny, degree, final_time = 16, 6, 1, 0.05
    nmodes = degree + 1
    zb = torch.zeros(nx, ny, nmodes, nmodes, dtype=torch.float64)
    zb[8:] = 2.5
    h = (ETA0 - zb).clamp_min(0.0)
    z = torch.zeros_like(zb)
    x, y, coeff, _, meta = solve_swe_2d(
        h, z, z, zb, nx=nx, ny=ny, degree=degree, final_time=final_time,
        domain=DOMAIN, cfl=0.3, well_balanced=True)
    eta = coeff[:, :, 0, 0, 0] + meta["zb_modes"][:, :, 0, 0]
    wet = (coeff[:, :, 0, 0, 0] > 1e-6)[:, 0]

    fig, ax = plt.subplots(figsize=(6.4, 3.8))
    ax.plot(x.numpy(), meta["zb_modes"][:, 0, 0, 0].numpy(), "k-", label=r"bed $z_b$")
    ax.plot(x.numpy()[wet.numpy()], eta[:, 0].numpy()[wet.numpy()], "o-",
            ms=3, color="#1f77b4", label=r"$\eta$ (wet cells)")
    ax.axhline(ETA0, color="grey", ls=":", lw=0.8)
    ax.set_xlabel("x")
    ax.set_ylabel("elevation [m]")
    ax.set_title("Still lake across a 2.5 m bed jump with a dry bank (P1, "
                 f"{meta['steps']} steps)")
    ax.legend(fontsize=8)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=150)
    plt.close(fig)
    caption = ("Bed jump on a cell face with the right half dry: the free surface "
               "stays on the straight line η = const and the dry cells stay dry.")
    return buf.getvalue(), caption



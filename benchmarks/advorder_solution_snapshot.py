"""Solution-field snapshot for the CASE-DG-ADVECT-ORDER robustness report.

Produces ``docs/figures/advorder_robust_solution.png``: the computed DG solution
against the analytic wave at ``t = 1`` (P1..P4 on ``N = 40``), plus the
pointwise error at the quadrature nodes.  The convergence table says *how fast*
the error vanishes; this figure shows *what* the error looks like (phase lag for
odd p, amplitude damping for even p -- the two admissible error mechanisms of an
upwind DG discretisation of a pure transport problem).

Cheap by construction (1-D, N=40, <=2000 steps per degree), so it runs on any
node and is regenerated by the publish script.

Run::

    PYTHONPATH=. python -m benchmarks.advorder_solution_snapshot
"""
from __future__ import annotations

import argparse
import json
import math
import pathlib

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import torch  # noqa: E402

from tensordg.advection_1d import solve_advection  # noqa: E402
from tensordg.runge_kutta import tableau_for_degree  # noqa: E402

FIG = pathlib.Path("docs/figures")
OUT = pathlib.Path("validation/advection_order_robustness")
NCELLS = 40
DEGREES = (1, 2, 3, 4)
CFL = 0.2
FINAL_TIME = 1.0
SPEED = 1.0


def _modal_values(coeff, degree, xq, ncells):
    """Evaluate the modal solution at reference nodes ``xq`` on every cell."""
    phi = []
    for k in range(degree + 1):
        c = np.zeros(k + 1)
        c[-1] = 1.0
        phi.append(np.polynomial.legendre.legval(xq, c))
    phi = np.stack(phi, axis=1)              # [q, modes]
    return coeff @ phi.T                     # [cells, q]


def main() -> dict:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(FIG / "advorder_robust_solution.png"))
    args = ap.parse_args()
    FIG.mkdir(parents=True, exist_ok=True)

    xq, wq = np.polynomial.legendre.leggauss(24)
    h = 1.0 / NCELLS
    fig, axes = plt.subplots(1, 2, figsize=(11.0, 4.2))
    summary = {}
    for d in DEGREES:
        tab = tableau_for_degree(d)
        centers, coeff, info = solve_advection(
            ncells=NCELLS, degree=d, final_time=FINAL_TIME, speed=SPEED,
            cfl=CFL, device="cpu", dtype=torch.float64,
            time_integrator=tab.name)
        uh = _modal_values(coeff.detach().numpy(), d, xq, NCELLS)
        x = (np.arange(NCELLS)[:, None] + 0.5 + 0.5 * xq[None, :]) * h
        exact = np.sin(2.0 * math.pi * (x - SPEED * FINAL_TIME))
        err = np.abs(uh - exact)
        l2 = float(np.sqrt(np.sum(0.5 * h * wq[None, :] * (uh - exact) ** 2)))
        summary[f"P{d}"] = {"l2": l2, "linf": float(err.max()),
                            "steps": int(info["steps"]), "dt": float(info["dt"]),
                            "tableau": tab.name}
        axes[0].plot(x.ravel(), uh.ravel(), ".", ms=1.6, label=f"P{d} {tab.name}")
        axes[1].semilogy(x.ravel(), np.maximum(err.ravel(), 1e-17), ".",
                         ms=1.6, label=f"P{d}")

    xe = np.linspace(0.0, 1.0, 2001)
    axes[0].plot(xe, np.sin(2.0 * math.pi * (xe - SPEED * FINAL_TIME)), "k-",
                 lw=1.0, label="exact $\\sin 2\\pi(x-t)$")
    axes[0].set_xlabel("x")
    axes[0].set_ylabel("u")
    axes[0].set_title(f"t = 1, N = {NCELLS}, cfl = {CFL}: computed vs exact")
    axes[0].legend(fontsize=7)
    axes[0].grid(alpha=0.3)
    axes[1].set_xlabel("x")
    axes[1].set_ylabel("$|u_h - u|$")
    axes[1].set_title("pointwise error at Gauss nodes")
    axes[1].grid(which="both", alpha=0.3)
    axes[1].legend(fontsize=7)
    fig.tight_layout()
    pathlib.Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(args.out, dpi=150)
    plt.close(fig)

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "solution_snapshot.json").write_text(json.dumps(
        {"ncells": NCELLS, "cfl": CFL, "final_time": FINAL_TIME,
         "degrees": list(DEGREES), "quadrature_nodes": 24,
         "errors": summary}, indent=1))
    print(json.dumps(summary, indent=1))
    return summary


if __name__ == "__main__":
    main()
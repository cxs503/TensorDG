"""Design-order verification of the 2-D compressible Navier--Stokes DG solver.

The module ``tensordg/ns_dg_2d.py`` verified four cases (inviscid limit, Couette
flow, pure conduction, decaying shear wave) but never established the *order of
accuracy* of the coupled convective + viscous operator: the shear-wave case
compares profiles on two meshes at one degree.  This driver closes that
verification debt with the textbook method of manufactured solutions (MMS) and
the volumetric ``source`` hook added for it.

Method
------
1. ``tensordg/mms_ns_2d.py`` (generated by ``tools/derive_ns_mms_source.py``)
   provides a smooth, 1-periodic, time-dependent primitive state and the
   symbolically derived conserved-variable source ``S`` that makes it an exact
   solution of the compressible Navier--Stokes equations with ``mu > 0``.
2. ``S`` is cross-checked against central finite differences of the *analytic*
   fields (an implementation-independent check of the generation step).
3. The solver integrates the manufactured problem from ``t = 0`` to ``T`` on a
   ladder of meshes for degrees 1, 2 (and 3), and the L2 error of every
   conserved variable against the analytic state is converted into an observed
   order of accuracy (EOC).  Design order is ``degree + 1``.

Numbers are written to ``validation/ns_dg_2d/mms_order.json`` and the figure to
``docs/figures/ns_dg_2d_mms_order.png``; no number in the report is typed by
hand.

Usage::

    PYTHONPATH=. python -m benchmarks.verify_ns_mms_order
"""
from __future__ import annotations

import json
import os

import numpy as np
import torch

from tensordg.euler_dg_2d import legendre_operators
from tensordg.mms_ns_2d import CP, mms_conserved, mms_primitives, mms_source
from tensordg.ns_dg_2d import solve_navier_stokes_dg_2d

MU = 0.01
PRANDTL = 0.71
KAPPA = MU * CP / PRANDTL
FINAL_TIME = 0.03
CFL = 0.1
CFL_VISCOUS = 0.5
DOMAIN = ((0.0, 1.0), (0.0, 1.0))
MESHES = (8, 16, 32)
DEGREES = (1, 2)
MESHES_HIGH = (8, 16)
FIELDS = ("density", "momentum_x", "momentum_y", "energy")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "validation", "ns_dg_2d")
FIG = os.path.join(ROOT, "docs", "figures")


# ---------------------------------------------------------------------------
# Exact solution helpers
# ---------------------------------------------------------------------------

def exact_conserved(x, y, t):
    """Analytic conserved state as a stacked tensor ``(..., 4)``."""
    return torch.stack(list(mms_conserved(x, y, t)), dim=-1)


def quadrature_coordinates(ncells, degree, quadrature, domain=DOMAIN):
    """Physical coordinates of every cell's quadrature nodes."""
    nx, ny = (ncells, ncells) if isinstance(ncells, int) else ncells
    (xmin, xmax), (ymin, ymax) = domain
    dx = (xmax - xmin) / nx
    dy = (ymax - ymin) / ny
    nodes, _weights, _basis, _derivative, _signs = legendre_operators(degree, quadrature)
    xi = nodes.double()
    x = xmin + (torch.arange(nx, dtype=torch.float64).view(nx, 1, 1, 1)
                + 0.5 * (xi.view(1, 1, -1, 1) + 1.0)) * dx
    y = ymin + (torch.arange(ny, dtype=torch.float64).view(1, ny, 1, 1)
                + 0.5 * (xi.view(1, 1, 1, -1) + 1.0)) * dy
    return x.expand(nx, ny, xi.numel(), xi.numel()), y.expand(nx, ny, xi.numel(), xi.numel()), dx, dy


def l2_error(numerical, exact, weights, dx, dy):
    """Quadrature L2 norm of ``numerical - exact`` and of ``exact``."""
    diff = numerical - exact
    w = weights.double()
    cell_weight = (w.view(-1, 1) * w.view(1, -1)) * (0.25 * dx * dy)
    weight = cell_weight.view(1, 1, *cell_weight.shape)
    err_sq = (diff ** 2 * weight).sum()
    ref_sq = (exact ** 2 * weight).sum()
    return float(torch.sqrt(err_sq)), float(torch.sqrt(ref_sq))


# ---------------------------------------------------------------------------
# Independent check of the derived source term
# ---------------------------------------------------------------------------

def _fd_source(x, y, t, mu, kappa, step=2.0e-4):
    """PDE source recomputed from the analytic fields with central differences.

    Deliberately independent of the sympy derivation: it differentiates the
    primitive fields numerically and rebuilds the flux divergences from the
    definitions in the ``ns_dg_2d`` docstring.
    """
    def prim(xx, yy, tt):
        return [torch.as_tensor(v) for v in mms_primitives(xx, yy, tt)]

    def conserved(xx, yy, tt):
        rho, u, v, p = prim(xx, yy, tt)
        energy = p / (1.4 - 1.0) + 0.5 * rho * (u * u + v * v)
        return [rho, rho * u, rho * v, energy]

    def inviscid(xx, yy, tt):
        rho, u, v, p = prim(xx, yy, tt)
        energy = p / (1.4 - 1.0) + 0.5 * rho * (u * u + v * v)
        fx = [rho * u, rho * u * u + p, rho * u * v, u * (energy + p)]
        fy = [rho * v, rho * u * v, rho * v * v + p, v * (energy + p)]
        return fx, fy

    def viscous(xx, yy, tt):
        rho, u, v, p = prim(xx, yy, tt)
        h = 1.0e-5

        def d(field, axis):
            if axis == 0:
                return (field(xx + h, yy, tt) - field(xx - h, yy, tt)) / (2 * h)
            return (field(xx, yy + h, tt) - field(xx, yy - h, tt)) / (2 * h)

        ux, uy = d(lambda a, b, c: prim(a, b, c)[1], 0), d(lambda a, b, c: prim(a, b, c)[1], 1)
        vx, vy = d(lambda a, b, c: prim(a, b, c)[2], 0), d(lambda a, b, c: prim(a, b, c)[2], 1)
        tx = d(lambda a, b, c: prim(a, b, c)[3] / prim(a, b, c)[0], 0)
        ty = d(lambda a, b, c: prim(a, b, c)[3] / prim(a, b, c)[0], 1)
        div = ux + vy
        txx = 2 * mu * ux - (2.0 / 3.0) * mu * div
        tyy = 2 * mu * vy - (2.0 / 3.0) * mu * div
        txy = mu * (uy + vx)
        fx = [torch.zeros_like(u), txx, txy, u * txx + v * txy + kappa * tx]
        fy = [torch.zeros_like(u), txy, tyy, u * txy + v * tyy + kappa * ty]
        return fx, fy

    step_t = 1.0e-5
    out = []
    u_t_plus, u_t_minus = conserved(x, y, t + step_t), conserved(x, y, t - step_t)
    fx_p, _ = inviscid(x + step, y, t)
    fx_m, _ = inviscid(x - step, y, t)
    _, fy_p = inviscid(x, y + step, t)
    _, fy_m = inviscid(x, y - step, t)
    vx_p, _ = viscous(x + step, y, t)
    vx_m, _ = viscous(x - step, y, t)
    _, vy_p = viscous(x, y + step, t)
    _, vy_m = viscous(x, y - step, t)
    for i in range(4):
        dudt = (u_t_plus[i] - u_t_minus[i]) / (2 * step_t)
        div_f = (fx_p[i] - fx_m[i]) / (2 * step) + (fy_p[i] - fy_m[i]) / (2 * step)
        div_fv = (vx_p[i] - vx_m[i]) / (2 * step) + (vy_p[i] - vy_m[i]) / (2 * step)
        out.append(dudt + div_f - div_fv)
    return torch.stack(out, dim=-1)


def source_selfcheck(points=24, seed=20260310):
    """Compare the symbolically derived source with the finite-difference one."""
    generator = torch.Generator().manual_seed(seed)
    x = 0.05 + 0.9 * torch.rand(points, generator=generator, dtype=torch.float64)
    y = 0.05 + 0.9 * torch.rand(points, generator=generator, dtype=torch.float64)
    time = torch.tensor(0.07, dtype=torch.float64)
    analytic = torch.stack(list(mms_source(x, y, time, MU, KAPPA)), dim=-1)
    numeric = _fd_source(x, y, time, MU, KAPPA)
    scale = float(analytic.abs().max())
    difference = float((analytic - numeric).abs().max())
    return {
        "points": points,
        "time": float(time),
        "max_abs_source": scale,
        "max_abs_difference": difference,
        "relative_difference": difference / scale,
        "tolerance": 1.0e-5,
        "pass": difference / scale < 1.0e-5,
    }


# ---------------------------------------------------------------------------
# Convergence study
# ---------------------------------------------------------------------------

def order_case(degree, ncells, final_time=FINAL_TIME, cfl=CFL, cfl_viscous=CFL_VISCOUS):
    """Run one manufactured-solution case and return its L2 errors."""
    quadrature = 2 * degree + 3

    def initial(x, y):
        return mms_primitives(x, y, torch.tensor(0.0, dtype=torch.float64))

    def source(x, y, time):
        return mms_source(x, y, time, MU, KAPPA)

    _x, _y, coeff, meta = solve_navier_stokes_dg_2d(
        initial,
        ncells=ncells,
        degree=degree,
        domain=DOMAIN,
        final_time=final_time,
        cfl=cfl,
        cfl_viscous=cfl_viscous,
        mu=MU,
        prandtl=PRANDTL,
        periodic=(True, True),
        quadrature=quadrature,
        source=source,
    )
    xq, yq, dx, dy = quadrature_coordinates(ncells, degree, quadrature)
    _nodes, weights, basis, _derivative, _signs = legendre_operators(degree, quadrature)
    at_quad = torch.einsum("xyklv,ak,bl->xyabv", coeff, basis.double(), basis.double())
    exact = exact_conserved(xq, yq, torch.tensor(final_time, dtype=torch.float64))
    errors = {}
    for index, name in enumerate(FIELDS):
        err, ref = l2_error(at_quad[..., index], exact[..., index], weights, dx, dy)
        errors[name] = {"l2": err, "relative_l2": err / ref}
    return {
        "degree": degree,
        "ncells": ncells if isinstance(ncells, int) else list(ncells),
        "quadrature": quadrature,
        "steps": meta["steps"],
        "diffusive_steps": meta["diffusive_steps"],
        "dt": meta["dt"],
        "errors": errors,
        "at_quad": at_quad.detach(),
        "exact": exact.detach(),
        "weights": weights.detach(),
        "dxdy": (dx, dy),
    }


def viscous_activity(points=200, seed=7):
    """Ratio of the viscous to the inviscid flux divergence in the manufactured state.

    A large ratio would mean the MMS barely exercises the BR1 operator; this
    diagnostic is reported so the verification cannot silently degrade into an
    Euler-only test.
    """
    generator = torch.Generator().manual_seed(seed)
    x = 0.05 + 0.9 * torch.rand(points, generator=generator, dtype=torch.float64)
    y = 0.05 + 0.9 * torch.rand(points, generator=generator, dtype=torch.float64)
    time = torch.tensor(0.03, dtype=torch.float64)
    viscous = _fd_source(x, y, time, MU, KAPPA) - _fd_source(x, y, time, 0.0, 0.0)
    inviscid = _fd_source(x, y, time, 0.0, 0.0)
    return {
        "max_abs_viscous_source": float(viscous.abs().max()),
        "max_abs_inviscid_source": float(inviscid.abs().max()),
        "ratio": float(viscous.abs().max() / inviscid.abs().max()),
    }


def temporal_control(degree=2, ncells=16):
    """Re-run one case with halved CFL values to bound the time-integration error."""
    reference = order_case(degree, ncells)
    refined = order_case(degree, ncells, cfl=CFL / 2, cfl_viscous=CFL_VISCOUS / 2)
    relative = {
        field: abs(refined["errors"][field]["l2"] - reference["errors"][field]["l2"])
        / reference["errors"][field]["l2"]
        for field in FIELDS
    }
    return {
        "degree": degree,
        "ncells": ncells,
        "reference_steps": reference["steps"],
        "refined_steps": refined["steps"],
        "relative_error_change": relative,
        "max_relative_change": max(relative.values()),
        "time_error_negligible": max(relative.values()) < 0.02,
    }


def observed_orders(cases, field="density"):
    """Observed order of accuracy between consecutive mesh levels of one degree."""
    orders = []
    for previous, current in zip(cases[:-1], cases[1:]):
        ratio = current["ncells"] / previous["ncells"]
        e_prev = previous["errors"][field]["l2"]
        e_curr = current["errors"][field]["l2"]
        orders.append(float(np.log(e_prev / e_curr) / np.log(ratio)))
    return orders


def main():
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(FIG, exist_ok=True)

    selfcheck = source_selfcheck()
    print("source self-check: relative difference = "
          f"{selfcheck['relative_difference']:.3e} ({'PASS' if selfcheck['pass'] else 'FAIL'})")
    if not selfcheck["pass"]:
        raise SystemExit("manufactured source failed its finite-difference cross-check")

    activity = viscous_activity()
    print(f"viscous/inviscid source ratio = {activity['ratio']:.3f}")
    control = temporal_control()
    print(f"temporal control: steps {control['reference_steps']} -> {control['refined_steps']}, "
          f"max relative error change {control['max_relative_change']:.3e}")

    study = {"source_selfcheck": selfcheck, "viscous_activity": activity,
             "temporal_control": control, "config": {
        "mu": MU, "prandtl": PRANDTL, "kappa": KAPPA,
        "final_time": FINAL_TIME, "domain": DOMAIN,
        "cfl": CFL, "cfl_viscous": CFL_VISCOUS,
        "meshes": list(MESHES), "degrees": list(DEGREES),
        "meshes_high_degree": list(MESHES_HIGH),
        "fields": list(FIELDS),
    }, "runs": [], "summary": []}

    finest = {}
    for degree in DEGREES:
        cases = []
        # Explicit diffusion costs O(h^-3), so degree 2 runs on two meshes only.
        ladder = MESHES if degree == 1 else MESHES[:2]
        for ncells in ladder:
            case = order_case(degree, ncells)
            orders = {field: observed_orders(cases + [case], field)[-1] if cases else None
                      for field in FIELDS}
            print(f"degree={degree} ncells={ncells:3d} steps={case['steps']:5d} | "
                  + " ".join(f"{f}: {case['errors'][f]['relative_l2']:.3e}%"
                             for f in FIELDS))
            entry = {key: value for key, value in case.items()
                     if key not in ("at_quad", "exact", "weights", "dxdy")}
            entry["observed_order"] = orders
            study["runs"].append(entry)
            cases.append(case)
            if ncells == ladder[-1]:
                finest[degree] = case

        for field in FIELDS:
            orders = observed_orders(cases, field)
            design = degree + 1
            study["summary"].append({
                "degree": degree,
                "field": field,
                "design_order": design,
                "observed_orders": orders,
                "mean_observed_order": float(np.mean(orders)),
                "finest_relative_l2": cases[-1]["errors"][field]["relative_l2"],
                "within_quarter_order_of_design": bool(np.mean(orders) >= design - 0.25),
            })

    high = []
    for ncells in MESHES_HIGH:
        case = order_case(3, ncells)
        entry = {key: value for key, value in case.items()
                 if key not in ("at_quad", "exact", "weights", "dxdy")}
        print(f"degree=3 ncells={ncells:3d} steps={case['steps']:5d} | "
              + " ".join(f"{f}: {case['errors'][f]['relative_l2']:.3e}%" for f in FIELDS))
        high.append(case)
        study["runs"].append(entry)
    for field in FIELDS:
        orders = observed_orders(high, field)
        study["summary"].append({
            "degree": 3,
            "field": field,
            "design_order": 4,
            "observed_orders": orders,
            "mean_observed_order": float(np.mean(orders)),
            "finest_relative_l2": high[-1]["errors"][field]["relative_l2"],
            "within_quarter_order_of_design": bool(np.mean(orders) >= 4 - 0.25),
        })

    study["all_within_quarter_order"] = all(
        entry["within_quarter_order_of_design"] for entry in study["summary"]
    )

    with open(os.path.join(OUT, "mms_order.json"), "w", encoding="utf-8") as handle:
        json.dump(study, handle, indent=2)

    _plot(study, finest)
    print("\nsummary")
    for entry in study["summary"]:
        print(f"  p={entry['degree']} {entry['field']:11s} "
              f"EOC={entry['observed_orders']} design={entry['design_order']} "
              f"{'OK' if entry['within_quarter_order_of_design'] else 'SHORT'}")
    print(f"\nall_within_quarter_order={study['all_within_quarter_order']}")
    return study


def _plot(study, finest):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    figure, (left, right) = plt.subplots(1, 2, figsize=(12.5, 4.8))

    colors = {1: "C0", 2: "C1", 3: "C2"}
    for degree in (1, 2, 3):
        runs = [run for run in study["runs"] if run["degree"] == degree]
        hs = np.array([1.0 / run["ncells"] for run in runs])
        errors = np.array([run["errors"]["density"]["relative_l2"] for run in runs])
        left.loglog(hs, errors, "o-", color=colors[degree],
                    label=f"degree {degree} (measured)")
        if len(hs) > 1:
            reference = errors[-1] * (hs / hs[-1]) ** (degree + 1)
            left.loglog(hs, reference, ":", color=colors[degree], alpha=0.8,
                        label=f"degree {degree} slope {degree + 1}")
    left.set_xlabel("mesh size h")
    left.set_ylabel(r"relative $L_2$ error of density")
    left.set_title("Manufactured-solution order verification\n(compressible NS, "
                   f"mu={MU}, Pr={PRANDTL})")
    left.grid(True, which="both", alpha=0.3)
    left.legend(fontsize=8)

    case = finest[max(finest)]
    dx, dy = case["dxdy"]
    error_field = (case["at_quad"] - case["exact"])[..., 0]
    _nodes, weights, _basis, _derivative, _signs = legendre_operators(
        case["degree"], case["quadrature"])
    cell_weight = (weights.view(-1, 1) * weights.view(1, -1)) * (0.25 * dx * dy)
    magnitude = (error_field ** 2 * cell_weight.view(1, 1, *cell_weight.shape)).sum(dim=(2, 3))
    grid = np.sqrt(magnitude.numpy())
    image = right.imshow(grid.T, origin="lower", extent=(0, 1, 0, 1),
                         cmap="magma", aspect="equal")
    right.set_title(f"Local L2 density error, degree {case['degree']}, "
                    f"{case['ncells']}x{case['ncells']} cells")
    right.set_xlabel("x")
    right.set_ylabel("y")
    figure.colorbar(image, ax=right, shrink=0.85, label="cell L2 error in density")
    figure.tight_layout()
    figure.savefig(os.path.join(FIG, "ns_dg_2d_mms_order.png"), dpi=150)
    plt.close(figure)


if __name__ == "__main__":
    main()
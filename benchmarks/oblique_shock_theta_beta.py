# Mach numbers and deflections of the case matrix.  ``FULL_THETAS`` is used
# wherever the wedge stays attached at every listed Mach; M = 1.5 detaches
# near 12 deg, so it gets its own (still >= 4) list.
MACH_LIST = (1.5, 2.0, 3.0, 4.0, 6.0, 10.0)
FULL_THETAS = (5.0, 10.0, 15.0, 20.0)
LOW_MACH_THETAS = (2.0, 5.0, 8.0, 10.0)
STRONG_PROBE_THETAS = (5.0, 10.0, 20.0)

# Predeclared tolerances (fixed before any run, see docs/report).
BETA_GATE_PCT = 2.0          # |beta_hat - beta| / beta <= 2 %
JUMP_GATE_PCT = 2.0          # |rho_hat/rho - 1|, |p_hat/p - 1| <= 2 %
GCI_GATE_PCT = 2.0           # Roache GCI of beta on the finest level < 2 %
HARD_FAIL_PCT = 15.0         # deviations above this are listed separately
GCI_SAFETY = 1.25            # Roache factor of safety Fs


# --------------------------------------------------------------------------- #
# branch algebra
# --------------------------------------------------------------------------- #
def detachment_angle(mach: float, gamma: float = GAMMA,
                     samples: int = 20001) -> tuple[float, float]:
    """``(theta_max, beta_detached)`` in degrees, located on a dense grid.

    ``theta(beta)`` is unimodal on ``(mu, 90)``; the maximum is refined by a
    golden-section search so the returned pair satisfies
    ``theta_from_beta(mach, beta_detached) == theta_max``.
    """
    mu = math.degrees(math.asin(1.0 / mach))
    grid = np.linspace(mu, 90.0, samples)
    values = [os.theta_from_beta(mach, float(b), gamma) for b in grid]
    i = int(np.argmax(values))
    lo = float(grid[max(i - 1, 0)])
    hi = float(grid[min(i + 1, len(grid) - 1)])
    best_b, best_t = float(grid[i]), float(values[i])
    for _ in range(200):                      # golden section on a unimodal map
        m1 = lo + 0.382 * (hi - lo)
        m2 = lo + 0.618 * (hi - lo)
        t1, t2 = os.theta_from_beta(mach, m1, gamma), os.theta_from_beta(mach, m2, gamma)
        if t1 >= t2:
            hi = m2
        else:
            lo = m1
        if hi - lo < 1e-11:
            break
    for candidate in (0.5 * (lo + hi), best_b):
        value = os.theta_from_beta(mach, candidate, gamma)
        if value >= best_t:
            best_b, best_t = candidate, value
    return best_t, best_b


def beta_from_theta_branch(mach: float, theta_deg: float, branch: str = "weak",
                           gamma: float = GAMMA) -> float:
    """Shock angle (deg) on ``branch`` in {"weak", "strong"} for a deflection.

    Raises when ``theta`` is outside ``(0, theta_max)``: past detachment there
    is no attached solution on either branch and returning a number would hide
    an invalid configuration.
    """
    theta_max, beta_det = detachment_angle(mach, gamma)
    if not 0.0 < theta_deg < theta_max:
        raise ValueError(f"theta = {theta_deg} deg outside (0, {theta_max:.4f}) "
                         f"at M = {mach}")
    mu = math.degrees(math.asin(1.0 / mach))
    if branch == "weak":
        lo, hi = mu + 1e-12, beta_det
    elif branch == "strong":
        lo, hi = beta_det, 90.0 - 1e-12
    else:
        raise ValueError("branch must be 'weak' or 'strong'")
    f_lo = os.theta_from_beta(mach, lo, gamma) - theta_deg
    f_hi = os.theta_from_beta(mach, hi, gamma) - theta_deg
    for _ in range(300):
        mid = 0.5 * (lo + hi)
        f_mid = os.theta_from_beta(mach, mid, gamma) - theta_deg
        if (f_mid > 0.0) == (f_lo > 0.0):
            lo, f_lo = mid, f_mid
        else:
            hi = mid
        if hi - lo < 1e-12:
            break
    return 0.5 * (lo + hi)


def normal_shock_ratios(mach: float, gamma: float = GAMMA) -> tuple[float, float]:
    """Closed-form normal-shock density / pressure ratios (1-D limit, M_n = M)."""
    rho_ratio = (gamma + 1.0) * mach ** 2 / ((gamma - 1.0) * mach ** 2 + 2.0)
    p_ratio = 1.0 + 2.0 * gamma / (gamma + 1.0) * (mach ** 2 - 1.0)
    return rho_ratio, p_ratio


# --------------------------------------------------------------------------- #
# anchors
# --------------------------------------------------------------------------- #
def _anchor_entry(mach: float, theta_deg: float, branch: str,
                  gamma: float = GAMMA) -> dict:
    beta = beta_from_theta_branch(mach, theta_deg, branch, gamma)
    solution = os.oblique_shock(mach, beta, gamma=gamma)
    residual = solution.diagnostics["rh_residual"]
    return {
        "mach": mach,
        "theta_deg": theta_deg,
        "branch": branch,
        "beta_deg": beta,
        "theta_roundtrip_deg": os.theta_from_beta(mach, beta, gamma),
        "theta_from_vectors_deg": solution.diagnostics["theta_from_vectors"],
        "normal_mach": solution.diagnostics["normal_mach"],
        "rho_ratio": solution.rho_ratio,
        "p_ratio": solution.p_ratio,
        "rho_downstream": solution.downstream.rho,
        "p_downstream": solution.downstream.p,
        "u_downstream": solution.downstream.u,
        "v_downstream": solution.downstream.v,
        "rh_residual_max": max(residual.values()),
        "rh_residual": residual,
    }


def build_anchors(gamma: float = GAMMA) -> dict:
    """Construct the anchor file content (all numbers computed, none typed)."""
    theta_max = {}
    for mach in MACH_LIST:
        t_max, b_det = detachment_angle(mach, gamma)
        theta_max[str(mach)] = {
            "theta_max_deg": t_max,
            "beta_detached_deg": b_det,
            "mach_angle_deg": math.degrees(math.asin(1.0 / mach)),
            "theta_max_check_deg": os.theta_from_beta(mach, b_det, gamma),
            "dtheta_dbeta_at_detachment": (
                os.theta_from_beta(mach, b_det + 1e-6, gamma)
                - os.theta_from_beta(mach, b_det - 1e-6, gamma)) / 2e-6,
        }

    table = []
    for mach in MACH_LIST:
        thetas = LOW_MACH_THETAS if mach < 2.5 else FULL_THETAS
        for theta in thetas:
            for branch in ("weak", "strong"):
                table.append(_anchor_entry(mach, theta, branch, gamma))

    # ---- limit checks ----------------------------------------------------- #
    checks = []

    def check(name, statement, criterion, values, status):
        checks.append({"name": name, "statement": statement,
                       "criterion": criterion, "values": values,
                       "status": status})

    # (1) theta -> 0 on the weak branch degenerates to the Mach line: beta -> mu
    #     and the jump disappears (normal Mach -> 1, so no shock exists).
    zero_rows = []
    ok = True
    for mach in MACH_LIST:
        mu = math.degrees(math.asin(1.0 / mach))
        gaps = {}
        for theta in (1e-3, 1e-4, 1e-6):
            beta_small = beta_from_theta_branch(mach, theta, "weak", gamma)
            gaps[theta] = beta_small - mu
        beta_tiny = beta_from_theta_branch(mach, 1e-6, "weak", gamma)
        theta_back = os.theta_from_beta(mach, beta_tiny, gamma) - 1e-6
        # beta - mu vanishes *linearly* in theta (dtheta/dbeta != 0 at mu), so the
        # limit is verified as a rate, not inside a fixed window at finite theta.
        approach_ratio = gaps[1e-3] / gaps[1e-4]
        rejected = False
        try:
            os.oblique_shock(mach, mu, gamma=gamma)      # normal Mach == 1
        except ValueError:
            rejected = True
        row_ok = (gaps[1e-6] < 1e-4 and abs(approach_ratio - 10.0) < 0.5
                  and abs(theta_back) < 1e-9 and rejected)
        ok = ok and row_ok
        zero_rows.append({"mach": mach, "mach_angle_deg": mu,
                          "beta_minus_mach_angle_at_theta_1e-3_deg": gaps[1e-3],
                          "beta_minus_mach_angle_at_theta_1e-4_deg": gaps[1e-4],
                          "beta_minus_mach_angle_at_theta_1e-6_deg": gaps[1e-6],
                          "linear_approach_ratio_1e-3_over_1e-4": approach_ratio,
                          "theta_roundtrip_minus_target_deg": theta_back,
                          "no_shock_at_mach_angle": rejected,
                          "status": "PASS" if row_ok else "FAIL"})
    check("theta_zero_weak_degenerates_to_mach_line",
          "theta -> 0 on the weak branch collapses onto the Mach line: "
          "beta -> mu = asin(1/M) with no jump (normal Mach -> 1 rejected)",
          "beta - mu at theta = 1e-6 deg is < 1e-4 deg, the approach is linear "
          "(ratio 10 +/- 0.5 when theta drops by 10) and oblique_shock(M, mu) raises",
          zero_rows, "PASS" if ok else "FAIL")

    # (2) theta -> 0 on the strong branch degenerates to the normal shock:
    #     beta -> 90 deg with the 1-D normal-shock ratios.
    strong_rows = []
    ok = True
    for mach in MACH_LIST:
        beta_tiny = beta_from_theta_branch(mach, 1e-6, "strong", gamma)
        solution = os.oblique_shock(mach, beta_tiny, gamma=gamma)
        rho_ref, p_ref = normal_shock_ratios(mach, gamma)
        rho_err = abs(solution.rho_ratio / rho_ref - 1.0)
        p_err = abs(solution.p_ratio / p_ref - 1.0)
        row_ok = abs(90.0 - beta_tiny) < 1e-2 and rho_err < 1e-6 and p_err < 1e-6
        ok = ok and row_ok
        strong_rows.append({"mach": mach, "beta_at_theta_1e-6_deg": beta_tiny,
                            "90_minus_beta_deg": 90.0 - beta_tiny,
                            "rho_ratio": solution.rho_ratio,
                            "rho_ratio_normal_shock": rho_ref,
                            "rho_rel_error": rho_err,
                            "p_ratio": solution.p_ratio,
                            "p_ratio_normal_shock": p_ref,
                            "p_rel_error": p_err,
                            "status": "PASS" if row_ok else "FAIL"})
    check("theta_zero_strong_degenerates_to_normal_shock",
          "theta -> 0 on the strong branch collapses onto beta = 90 deg with the "
          "1-D normal-shock ratios of the same M",
          "|90 - beta(theta=1e-6)| < 1e-2 deg and RH ratios match the 1-D "
          "closed form to 1e-6 relative",
          strong_rows, "PASS" if ok else "FAIL")

    # (3) at theta_max the two roots merge: beta_weak - beta_strong -> 0, and
    #     theta_from_beta(beta_detached) == theta_max with dtheta/dbeta = 0.
    merge_rows = []
    ok = True
    for mach in MACH_LIST:
        t_max, b_det = detachment_angle(mach, gamma)
        row = {"mach": mach, "theta_max_deg": t_max, "beta_detached_deg": b_det}
        row_ok = abs(os.theta_from_beta(mach, b_det, gamma) - t_max) < 1e-9
        for delta in (0.5, 0.1, 0.01):
            theta = t_max - delta
            b_w = beta_from_theta_branch(mach, theta, "weak", gamma)
            b_s = beta_from_theta_branch(mach, theta, "strong", gamma)
            row[f"branch_gap_deg_at_theta_max_minus_{delta}"] = b_s - b_w
            if not b_s - b_w >= 0.0:
                row_ok = False
        row["dtheta_dbeta_at_detachment"] = (
            os.theta_from_beta(mach, b_det + 1e-6, gamma)
            - os.theta_from_beta(mach, b_det - 1e-6, gamma)) / 2e-6
        row_ok = row_ok and abs(row["dtheta_dbeta_at_detachment"]) < 1e-4
        row_ok = row_ok and (row["branch_gap_deg_at_theta_max_minus_0.01"]
                             < row["branch_gap_deg_at_theta_max_minus_0.5"])
        row["status"] = "PASS" if row_ok else "FAIL"
        ok = ok and row_ok
        merge_rows.append(row)
    check("theta_max_merges_the_two_branches",
          "the weak and strong roots coincide at the detachment angle: the "
          "branch gap shrinks monotonically as theta -> theta_max and "
          "dtheta/dbeta vanishes there",
          "|theta(beta_det) - theta_max| < 1e-9 deg, |dtheta/dbeta| < 1e-4, "
          "branch gap decreasing in theta_max - theta",
          merge_rows, "PASS" if ok else "FAIL")

    # (4) branch ordering / continuity: weak < strong for every theta < theta_max,
    #     beta_strong monotone increasing in theta, and no root outside (mu, 90).
    continuity_rows = []
    ok = True
    for mach in MACH_LIST:
        t_max, _ = detachment_angle(mach, gamma)
        mu = math.degrees(math.asin(1.0 / mach))
        thetas = np.linspace(0.05 * t_max, 0.95 * t_max, 19)
        b_w = [beta_from_theta_branch(mach, float(t), "weak", gamma) for t in thetas]
        b_s = [beta_from_theta_branch(mach, float(t), "strong", gamma) for t in thetas]
        ordered = all(w < s for w, s in zip(b_w, b_s))
        weak_monotone = all(a < b for a, b in zip(b_w, b_w[1:]))
        # the strong root runs from beta = 90 deg (theta -> 0, normal shock) down
        # to beta_detached (theta -> theta_max): it decreases with deflection.
        strong_monotone = all(a > b for a, b in zip(b_s, b_s[1:]))
        in_range = (min(b_w) > mu and max(b_s) < 90.0)
        row_ok = ordered and weak_monotone and strong_monotone and in_range
        ok = ok and row_ok
        continuity_rows.append({
            "mach": mach, "mu_deg": mu, "beta_weak_min_deg": min(b_w),
            "beta_weak_max_deg": max(b_w), "beta_strong_min_deg": min(b_s),
            "beta_strong_max_deg": max(b_s),
            "weak_below_strong": ordered,
            "weak_increasing_in_theta": weak_monotone,
            "strong_decreasing_in_theta": strong_monotone,
            "roots_inside_mach_angle_to_90": in_range,
            "status": "PASS" if row_ok else "FAIL"})
    check("branch_continuity_and_ordering",
          "weak and strong roots are distinct and correctly ordered for every "
          "theta < theta_max, both stay inside (mu, 90); the weak root increases "
          "with the deflection while the strong root decreases from 90 deg "
          "(normal shock) to beta_detached",
          "weak < strong, weak increasing and strong decreasing in theta, "
          "roots in (mu, 90)",
          continuity_rows, "PASS" if ok else "FAIL")

    # (5) the jump algebra closes: RH residuals ~ 0 and the deflection read off
    #     the two velocity vectors equals the theta--beta--M value.
    worst_rh = max(row["rh_residual_max"] for row in table)
    worst_theta = max(abs(row["theta_from_vectors_deg"] - row["theta_deg"])
                      for row in table)
    check("jump_closure_on_both_branches",
          "every anchor state pair satisfies the four Rankine--Hugoniot jump "
          "conditions and the velocity-vector deflection equals the "
          "theta--beta--Mach deflection",
          "max RH residual < 1e-12, max |theta_vectors - theta| < 1e-9 deg",
          {"entries": len(table), "max_rh_residual": worst_rh,
           "max_theta_deviation_deg": worst_theta},
          "PASS" if worst_rh < 1e-12 and worst_theta < 1e-9 else "FAIL")

    return {
        "anchor_id": ANCHOR_ID,
        "schema": "theta-beta-mach-anchors/1",
        "generated_by": "benchmarks.oblique_shock_theta_beta::build_anchors",
        "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "commit": _git_commit(),
        "gamma": gamma,
        "reference": ("theta--beta--Mach relation and Rankine--Hugoniot jump "
                      "conditions, Anderson, Modern Compressible Flow, 3rd ed., "
                      "ch. 3-4; all values recomputed here, none transcribed"),
        "assumptions": {"upstream": "rho=1, p=1, u = M*sqrt(gamma), v = 0",
                        "front": "straight, angle beta to the x axis",
                        "branch": "weak = selected in wedge flow; strong = "
                                  "non-unique, needs downstream back pressure"},
        "mach_list": list(MACH_LIST),
        "theta_list_full": list(FULL_THETAS),
        "theta_list_low_mach": list(LOW_MACH_THETAS),
        "detachment": theta_max,
        "limit_checks": checks,
        "table": table,
    }


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()
    except Exception:                                    # pragma: no cover
        return "unknown"


# --------------------------------------------------------------------------- #
# DG case matrix
# --------------------------------------------------------------------------- #
@dataclass
class MatrixCase:
    mach: float
    theta_deg: float
    branch: str
    degree: int
    ncells: int = 32
    final_time: float = 0.05
    cfl: float = 0.2
    limiter: str | None = None
    tvb_constant: float = 1.0

    @property
    def case_id(self) -> str:
        return f"M{self.mach:g}_th{self.theta_deg:g}_{self.branch}_P{self.degree}"


def build_matrix(ncells: int = 32, final_time: float = 0.05,
                 degrees=(1, 2), strong: bool = True) -> list[MatrixCase]:
    cases = []
    for mach in MACH_LIST:
        thetas = LOW_MACH_THETAS if mach < 2.5 else FULL_THETAS
        for theta in thetas:
            for degree in degrees:
                cases.append(MatrixCase(mach, theta, "weak", degree,
                                        ncells=ncells, final_time=final_time))
    if strong:
        for mach in (3.0, 6.0):
            for theta in STRONG_PROBE_THETAS:
                for degree in degrees:
                    cases.append(MatrixCase(mach, theta, "strong", degree,
                                            ncells=ncells,
                                            final_time=final_time))
    return cases


def run_matrix_case(case: MatrixCase, gamma: float = GAMMA) -> dict:
    """Run one matrix entry and measure it against its anchor values."""
    beta_exact = beta_from_theta_branch(case.mach, case.theta_deg, case.branch,
                                       gamma)
    solution = os.oblique_shock(case.mach, beta_exact, gamma=gamma)
    initial = os.oblique_shock_initial(solution)
    started = time.time()
    x, y, coeff, metadata = solve_euler_dg_2d(
        initial, ncells=(case.ncells, case.ncells), degree=case.degree,
        final_time=case.final_time, cfl=case.cfl, limiter=case.limiter,
        tvb_constant=case.tvb_constant, periodic=(False, False),
        dtype=torch.float64,
    )
    wall = time.time() - started
    measured = os.measure_oblique_shock(x, y, coeff, solution)
    centroid = measure_front_centroid(x, y, coeff, solution)
    record = {
        "case_id": case.case_id,
        "mach": case.mach,
        "theta_deg": case.theta_deg,
        "branch": case.branch,
        "degree": case.degree,
        "ncells": case.ncells,
        "final_time": case.final_time,
        "cfl": case.cfl,
        "limiter": case.limiter or "none",
        "steps": metadata["steps"],
        "wall_s": round(wall, 2),
        "beta_exact_deg": beta_exact,
        "beta_hat_deg": measured["beta_hat_deg"],
        "beta_dev_deg": measured["beta_error_deg"],
        "beta_dev_pct": (None if measured["beta_error_deg"] is None
                         else 100.0 * measured["beta_error_deg"] / beta_exact),
        "rho_ratio_exact": solution.rho_ratio,
        "rho_ratio_hat": measured["rho_ratio_hat"],
        "rho_dev_pct": 100.0 * measured["rho_ratio_error"],
        "p_ratio_exact": solution.p_ratio,
        "p_ratio_hat": measured["p_ratio_hat"],
        "p_dev_pct": 100.0 * measured["p_ratio_error"],
        "theta_exact_deg": solution.theta_deg,
        "theta_hat_deg": measured["theta_hat_deg"],
        "theta_dev_deg": measured["theta_error_deg"],
        "preserve_l1": measured["preserve_l1"],
        "rh_residual_max": max(solution.diagnostics["rh_residual"].values()),
        "beta_hat_centroid_deg": centroid["beta_hat_centroid_deg"],
        "beta_dev_centroid_pct": (None if centroid["beta_error_centroid_deg"] is None
                                  else 100.0 * centroid["beta_error_centroid_deg"]
                                  / beta_exact),
        "beta_hat_centroid_plain_deg": centroid["beta_hat_centroid_plain_deg"],
        "beta_dev_centroid_plain_pct": (
            None if centroid["beta_error_centroid_plain_deg"] is None
            else 100.0 * centroid["beta_error_centroid_plain_deg"] / beta_exact),
        "centroid_clipped_fraction": centroid["centroid_clipped_fraction"],
        "centroid_scatter_deg": centroid["centroid_scatter_deg"],
    }
    # Primary angle metric: robust gradient-centroid fit (see
    # measure_front_centroid).  The mid-level-crossing value from
    # benchmarks.oblique_shock is kept in the table as the diagnostic estimator.
    record["gate_beta_2pct"] = (record["beta_dev_centroid_pct"] is not None
                                and record["beta_dev_centroid_pct"] <= BETA_GATE_PCT)
    record["gate_beta_crossing_2pct"] = (record["beta_dev_pct"] is not None
                                         and record["beta_dev_pct"] <= BETA_GATE_PCT)
    record["gate_jump_2pct"] = (record["rho_dev_pct"] <= JUMP_GATE_PCT
                                and record["p_dev_pct"] <= JUMP_GATE_PCT)
    record["verdict"] = ("PASS" if record["gate_beta_2pct"] and record["gate_jump_2pct"]
                         else "FAIL")
    worst = max([v for v in (record["beta_dev_centroid_pct"], record["beta_dev_pct"],
                             record["rho_dev_pct"], record["p_dev_pct"])
                 if v is not None])
    record["max_dev_pct"] = worst
    record["hard_fail_15pct"] = worst > HARD_FAIL_PCT
    record["note"] = _attribution(record)
    return record


def _attribution(record: dict) -> str:
    """One-line diagnosis for a case, empty when it passed."""
    if record["verdict"] == "PASS":
        return ""
    reasons = []
    if record["beta_hat_centroid_deg"] is None:
        reasons.append("shock front not detected from the numerical density field")
    elif record["beta_dev_centroid_pct"] > BETA_GATE_PCT:
        reasons.append("front angle drift: the smeared front migrates under the "
                       "transmissive outflow while the interior state relaxes")
    if record["rho_dev_pct"] > JUMP_GATE_PCT or record["p_dev_pct"] > JUMP_GATE_PCT:
        reasons.append("post-shock plateau not converged: Gibbs oscillations "
                       "at P%d feed back into the plateau average" % record["degree"])
    if (record["beta_dev_pct"] is not None
            and record["beta_dev_centroid_pct"] is not None
            and record["beta_dev_pct"] > BETA_GATE_PCT
            <= record["beta_dev_centroid_pct"]):
        reasons.append("mid-level-crossing estimator biased by the one-cell "
                       "staircase of the smeared front (diagnostic only)")
    if record["branch"] == "strong":
        reasons.append("strong branch is non-unique in a free subsonic outflow "
                       "(no downstream back pressure), so it is only expected to "
                       "hold while the initial data are not perturbed")
    return "; ".join(reasons)



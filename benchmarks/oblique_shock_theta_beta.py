def _filter_cases(cases, args):
    selected = cases
    if args.machs:
        wanted = {float(value) for value in args.machs.split(",")}
        selected = [case for case in selected if case.mach in wanted]
    if args.degrees:
        wanted = {int(value) for value in args.degrees.split(",")}
        selected = [case for case in selected if case.degree in wanted]
    if args.branches:
        wanted = {value.strip() for value in args.branches.split(",")}
        selected = [case for case in selected if case.branch in wanted]
    if not selected:
        raise SystemExit("case filter selected nothing")
    return selected


def merge_parts(output_dir: Path = OUTPUT_DIR, pattern: str = "part_*.csv",
                target: str = "case_matrix.csv") -> Path:
    """Concatenate the parallel part files into the published case matrix."""
    output_dir = Path(output_dir)
    rows = []
    for path in sorted(output_dir.glob(pattern)):
        with open(path) as handle:
            rows.extend(list(csv.DictReader(handle)))
    # a case can appear in more than one part when the Mach split overlaps;
    # keep one row per case_id (the runs are deterministic)
    unique = {}
    for row in rows:
        unique.setdefault(row["case_id"], row)
    rows = list(unique.values())
    order = {mach: index for index, mach in enumerate(MACH_LIST)}
    rows.sort(key=lambda row: (order.get(float(row["mach"]), 99),
                               float(row["theta_deg"]),
                               0 if row["branch"] == "weak" else 1,
                               int(row["degree"])))
    out = output_dir / target
    with open(out, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_FIELDS)
        writer.writeheader()
        for row in rows:
            writer.writerow({key: row.get(key, "") for key in CSV_FIELDS})
    print(f"merged {len(rows)} rows -> {out}")
    return out



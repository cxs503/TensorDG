# grid convergence (Roache GCI)
# --------------------------------------------------------------------------- #
def gci_three_level(fine: float, medium: float, coarse: float,
                    ratio: float = 2.0, safety: float = GCI_SAFETY) -> dict:
    """Roache grid convergence index from three levels (fine, medium, coarse).

    Returns the observed order ``p``, the Richardson limit, the relative
    differences and ``GCI_fine`` (percent).  When the differences do not decay
    in a resolvable way -- oscillatory convergence or no decay at all, i.e. an
    observed order outside ``(0.2, 8)`` -- a first-order rate is used instead
    (conservative) and the result is flagged ``order_estimated=False``.
    """
    e_medium = abs(medium - fine)
    e_coarse = abs(coarse - medium)
    estimate = {"fine": fine, "medium": medium, "coarse": coarse, "ratio": ratio}
    p_obs = None
    if e_medium > 0.0 and e_coarse > 0.0:
        argument = e_coarse / e_medium
        if argument > 0.0:
            p_obs = math.log(argument) / math.log(ratio)
    if p_obs is None or not (0.2 < p_obs < 8.0):
        p_used, estimated = 1.0, False
    else:
        p_used, estimated = p_obs, True
    denominator = ratio ** p_used - 1.0
    gci_fine = safety * e_medium / (max(abs(fine), 1e-30) * denominator) * 100.0
    extrapolated = fine + (fine - medium) / denominator
    estimate.update({"observed_order": p_obs, "order_used": p_used,
                     "order_estimated": estimated,
                     "gci_fine_pct": gci_fine,
                     "richardson_limit": extrapolated,
                     "rel_change_medium_fine_pct":
                         100.0 * e_medium / max(abs(fine), 1e-30),
                     "rel_change_coarse_medium_pct":
                         100.0 * e_coarse / max(abs(medium), 1e-30)})
    return estimate


def run_convergence(cases: list[MatrixCase] | None = None,
                    levels: tuple[int, int, int] = (16, 32, 64),
                    output_dir: Path = OUTPUT_DIR,
                    gamma: float = GAMMA) -> dict:
    """Three-level refinement of the recovered shock angle and jump ratios."""
    if cases is None:
        cases = [MatrixCase(3.0, 15.0, "weak", 2),
                 MatrixCase(6.0, 10.0, "weak", 1)]
    entries = []
    for base in cases:
        rows = []
        for ncells in levels:
            refined = MatrixCase(base.mach, base.theta_deg, base.branch,
                                 base.degree, ncells=ncells,
                                 final_time=base.final_time, cfl=base.cfl,
                                 limiter=base.limiter)
            rows.append(run_matrix_case(refined, gamma))
        beta = [row["beta_hat_deg"] for row in rows]
        rho = [row["rho_ratio_hat"] for row in rows]
        prs = [row["p_ratio_hat"] for row in rows]
        entry = {
            "case_id": base.case_id,
            "mach": base.mach,
            "theta_deg": base.theta_deg,
            "branch": base.branch,
            "degree": base.degree,
            "final_time": base.final_time,
            "levels": list(levels),
            "beta_hat_deg": beta,
            "beta_exact_deg": rows[0]["beta_exact_deg"],
            "beta_abs_dev_deg": [row["beta_dev_deg"] for row in rows],
            "rho_ratio_hat": rho,
            "rho_ratio_exact": rows[0]["rho_ratio_exact"],
            "p_ratio_hat": prs,
            "p_ratio_exact": rows[0]["p_ratio_exact"],
            "gci_beta": None if any(v is None for v in beta) else
                        gci_three_level(beta[2], beta[1], beta[0]),
            "gci_rho": None if any(v is None for v in rho) else
                       gci_three_level(rho[2], rho[1], rho[0]),
            "gci_p": None if any(v is None for v in prs) else
                     gci_three_level(prs[2], prs[1], prs[0]),
        }
        gci_beta = entry["gci_beta"]["gci_fine_pct"] if entry["gci_beta"] else None
        entry["gate_gci_beta_2pct"] = (gci_beta is not None
                                       and gci_beta < GCI_GATE_PCT)
        entry["runs"] = rows
        entries.append(entry)
        print(f"[conv {base.case_id}] beta={beta} GCI_beta="
              f"{None if gci_beta is None else round(gci_beta, 4)}% "
              f"gate={entry['gate_gci_beta_2pct']}", flush=True)
    verdict = all(entry["gate_gci_beta_2pct"] for entry in entries)
    payload = {
        "study": "oblique_shock_grid_convergence",
        "method": "Roache GCI, three levels, refinement ratio 2, Fs=1.25",
        "declared_gate_pct": GCI_GATE_PCT,
        "levels": list(levels),
        "verdict": "PASS" if verdict else "FAIL",
        "cases": entries,
    }
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    with open(output_dir / "convergence.json", "w") as handle:
        json.dump(payload, handle, indent=2)
    print(f"convergence verdict: {payload['verdict']}", flush=True)
    return payload



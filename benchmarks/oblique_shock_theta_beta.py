def _pct(value):
    return "n/a" if value is None else f"{value:.3f}%"


def _fmt(value):
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return f"{value:.10g}"
    return value


def _failed_record(case: MatrixCase, error: Exception) -> dict:
    """Row for a run the solver refused or that blew up (kept, not dropped)."""
    try:
        beta_exact = beta_from_theta_branch(case.mach, case.theta_deg, case.branch)
    except ValueError:
        beta_exact = float("nan")
    record = {key: None for key in CSV_FIELDS}
    record.update({
        "case_id": case.case_id, "mach": case.mach, "theta_deg": case.theta_deg,
        "branch": case.branch, "degree": case.degree, "ncells": case.ncells,
        "final_time": case.final_time, "cfl": case.cfl,
        "limiter": case.limiter or "none", "steps": None, "wall_s": None,
        "beta_exact_deg": beta_exact, "gate_beta_2pct": False,
        "gate_beta_crossing_2pct": False, "gate_jump_2pct": False,
        "verdict": "FAIL", "max_dev_pct": float("inf"),
        "hard_fail_15pct": True,
        "note": (f"solver aborted ({type(error).__name__}: {error}); the exact "
                 f"two-state strong-branch field is not sustained by the "
                 f"transmissive outflow -- non-unique branch without a "
                 f"downstream back pressure"),
    })
    return record


def run_matrix(cases: list[MatrixCase] | None = None,
               output_dir: Path = OUTPUT_DIR, csv_name: str = "case_matrix.csv",
               append: bool = False) -> list[dict]:
    cases = build_matrix() if cases is None else cases
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / csv_name
    write_header = not append or not path.exists()
    records = []
    with open(path, "a" if append else "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_FIELDS)
        if write_header:
            writer.writeheader()
        for case in cases:
            try:
                record = run_matrix_case(case)
            except Exception as error:      # positivity failure, blow-up, ...
                record = _failed_record(case, error)
                print(f"[{case.case_id}] ERROR {type(error).__name__}: {error}",
                      flush=True)
            writer.writerow({key: _fmt(record.get(key)) for key in CSV_FIELDS})
            handle.flush()
            records.append(record)
            print(f"[{record['case_id']}] "
                  f"beta_dev={_pct(record['beta_dev_centroid_pct'])} "
                  f"(crossing {_pct(record['beta_dev_pct'])}) "
                  f"rho_dev={_pct(record['rho_dev_pct'])} "
                  f"p_dev={_pct(record['p_dev_pct'])} "
                  f"preserve={record['preserve_l1']} -> {record['verdict']}",
                  flush=True)
    return records



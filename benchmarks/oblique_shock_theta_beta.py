# robust front-angle estimator
# --------------------------------------------------------------------------- #
def front_centroid_offsets(x, y, coeff, solution, x0: float = 0.5,
                           y0: float = 0.5, boundary_margin: float = 0.12,
                           n_rays: int = 81, window_frac: float = 0.35,
                           samples: int = 401, half_window: float = 0.25):
    """Per-ray front position from the centroid of ``|d rho / ds|``.

    The mid-level crossing used by :func:`benchmarks.oblique_shock.measure_oblique_shock`
    reads the value of a *single* interpolated sample, so at shallow shock angles
    and large density ratios the one-cell staircase of the smeared front biases
    it by a fraction of a cell -- enough to tilt the fitted line (found at
    M = 6, theta = 15: 16 % angle error while the field itself was preserved to
    3.6 %).  The centroid

        s_c = \int s |d rho/ds| ds / \int |d rho/ds| ds

    integrates the whole jump, so it is insensitive to the profile shape, to the
    smearing width and to single-sample noise, while it still uses the numerical
    density field only (the exact solution enters solely through the normal
    direction, exactly as for the crossing estimator).

    Only rays whose full sampling window lies inside the interior box (at least
    ``boundary_margin`` away from every face) *and* inside the central
    ``half_window`` fraction of the front are used: a truncated window biases an
    integral estimator, and where the front leaves the domain through a
    transmissive face the numerical front is visibly displaced (up to two cells
    at M = 6), which would tilt a fit spanning those rays.

    Returns ``(offsets, points, s_centroids)``: the tangent offsets of the usable
    rays, the corresponding 2-D front points and the ray-wise centroid offsets.
    """
    from benchmarks.oblique_shock import _exact_front_line, _interp
    fields = __import__("tensordg.euler_dg_2d", fromlist=["cell_fields"]).cell_fields(coeff)
    density = fields["density"].cpu().numpy()
    xc, yc = x.cpu().numpy(), y.cpu().numpy()
    h = min(xc[1] - xc[0], yc[1] - yc[0])
    x_min = xc[0] - 0.5 * (xc[1] - xc[0]) + boundary_margin
    x_max = xc[-1] + 0.5 * (xc[1] - xc[0]) - boundary_margin
    y_min = yc[0] - 0.5 * (yc[1] - yc[0]) + boundary_margin
    y_max = yc[-1] + 0.5 * (yc[1] - yc[0]) - boundary_margin
    box = (x_min, x_max, y_min, y_max)
    extent = max(x_max - x_min, y_max - y_min)
    origin, n, t = _exact_front_line(solution, x0, y0, None)
    offsets = np.linspace(-0.45 * extent, 0.45 * extent, n_rays)
    s_samples = np.linspace(-window_frac * extent, window_frac * extent, samples)
    used_offsets, points, centroids = [], [], []
    for offset in offsets:
        start = np.array([origin[0] + offset * t[0], origin[1] + offset * t[1]])
        px = start[0] + s_samples * n[0]
        py = start[1] + s_samples * n[1]
        keep = ((px > box[0]) & (px < box[1]) & (py > box[2]) & (py < box[3]))
        # A truncated sampling window biases an integral estimator, and the
        # front is visibly displaced where it leaves the domain through a
        # transmissive face, so only rays whose *whole* window lies inside the
        # interior box and inside the central part of the front are used.
        if not keep.all() or abs(offset) > half_window * extent:
            continue
        values = _interp(density, xc, yc, px, py)
        s_w = s_samples
        v_w = values
        gradient = np.abs(np.gradient(v_w, s_w))
        total = gradient.sum()
        if total <= 0.0:
            continue
        s_c = float((s_w * gradient).sum() / total)
        used_offsets.append(offset)
        centroids.append(s_c)
        points.append((start[0] + s_c * n[0], start[1] + s_c * n[1]))
    return np.array(used_offsets), np.array(points), np.array(centroids)


def measure_front_centroid(x, y, coeff, solution, x0: float = 0.5,
                           y0: float = 0.5, boundary_margin: float = 0.12,
                           n_rays: int = 81, clip_sigma: float = 2.5) -> dict:
    """Front angle from the gradient centroid, plus its scatter diagnostics."""
    offsets, points, centroids = front_centroid_offsets(
        x, y, coeff, solution, x0=x0, y0=y0, boundary_margin=boundary_margin,
        n_rays=n_rays)
    result = {"beta_hat_centroid_deg": None, "beta_error_centroid_deg": None,
              "centroid_scatter_deg": None, "centroid_rays": int(len(offsets))}
    if len(points) < 5:
        return result

    def fit(mask):
        points_here = points[mask]
        centred = points_here - points_here.mean(axis=0)
        _, _, vt = np.linalg.svd(centred, full_matrices=False)
        direction = vt[0]
        if direction[0] < 0.0 or (abs(direction[0]) < 1e-9 and direction[1] < 0.0):
            direction = -direction
        angle = math.degrees(math.atan2(direction[1], direction[0]))
        residual_here = (centroids - math.tan(math.radians(angle)) * offsets)[mask]
        return angle, residual_here

    plain_mask = np.ones(len(points), dtype=bool)
    beta_plain, residual_plain = fit(plain_mask)
    # Iterative MAD clipping: a localized front distortion at one end of the
    # measurement window (seen at high M where the front leaves the domain
    # through a transmissive face) tilts a plain least-squares fit by whole
    # degrees, so the primary estimator rejects rays further than
    # ``clip_sigma * 1.4826 * MAD`` from the line.  The plain fit is still
    # reported so the sensitivity of the number is visible.
    mask = plain_mask
    for _ in range(5):
        median = np.median(residual_plain)
        mad = np.median(np.abs(residual_plain - median))
        if mad <= 0.0:
            break
        keep = np.abs(residual_plain - median) <= clip_sigma * 1.4826 * mad
        if keep.all() or keep.sum() < 5:
            break
        beta_robust, residual_robust = fit(keep)
        mask = keep
        residual_plain = residual_robust
        beta_plain_keep = beta_robust
    beta_robust, residual_robust = fit(mask)
    result.update({
        "beta_hat_centroid_deg": beta_robust,
        "beta_error_centroid_deg": abs(beta_robust - solution.beta_deg),
        "beta_hat_centroid_plain_deg": beta_plain,
        "beta_error_centroid_plain_deg": abs(beta_plain - solution.beta_deg),
        "centroid_rays_used": int(mask.sum()),
        "centroid_rays_total": int(len(points)),
        "centroid_clipped_fraction": float(1.0 - mask.sum() / len(points)),
        "centroid_scatter_deg": math.degrees(
            math.atan(np.std(residual_robust) * math.sqrt(12.0)
                      / max(np.ptp(offsets[mask]), 1e-12))),
    })
    return result



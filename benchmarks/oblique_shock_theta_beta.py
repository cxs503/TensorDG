# attribution study for the shallow-angle (high M, small theta) hard failures
# --------------------------------------------------------------------------- #
def diagnose_shallow(mach: float = 6.0, theta_deg: float = 5.0,
                     degree: int = 1, ncells: int = 32,
                     times=(0.01, 0.02, 0.05), margins=(0.12, 0.20),
                     finer: int | None = 64,
                     output_dir: Path = OUTPUT_DIR,
                     gamma: float = GAMMA) -> dict:
    """Is the shallow-angle shock-angle error drift, or a measurement floor?

    Three knobs, each answering one question:

    * ``time`` -- if the deviation grows with time the field is really moving
      (drift seeded by the transmissive faces); if it is flat the error is
      already in the projected initial data / measurement;
    * ``boundary_margin`` -- shrinking the measurement window away from the
      boundaries separates a boundary-driven error from a whole-domain effect;
    * ``finer`` mesh -- grid dependence distinguishes a resolution effect from a
      physical drift.

    Writes ``diagnose_M<mach>_th<theta>_P<degree>.json`` and returns the payload.
    """
    beta_exact = beta_from_theta_branch(mach, theta_deg, "weak", gamma)
    solution = os.oblique_shock(mach, beta_exact, gamma=gamma)
    initial = os.oblique_shock_initial(solution)
    runs = []
    for ncells_here in ([ncells] if finer is None else [ncells, finer]):
        for final_time in times:
            started = time.time()
            try:
                x, y, coeff, metadata = solve_euler_dg_2d(
                    initial, ncells=(ncells_here, ncells_here), degree=degree,
                    final_time=final_time, cfl=0.2, periodic=(False, False),
                    dtype=torch.float64)
            except Exception as error:
                runs.append({"ncells": ncells_here, "final_time": final_time,
                             "boundary_margin": None, "degree": degree,
                             "steps": None, "beta_hat_deg": None,
                             "beta_dev_pct": None, "rho_dev_pct": None,
                             "p_dev_pct": None, "preserve_l1": None,
                             "error": f"{type(error).__name__}: {error}"})
                print(f"[diag N{ncells_here} t={final_time}] aborted: {error}",
                      flush=True)
                continue
            for margin in margins:
                measured = os.measure_oblique_shock(
                    x, y, coeff, solution, boundary_margin=margin)
                centroid = measure_front_centroid(x, y, coeff, solution,
                                                  boundary_margin=margin)
                runs.append({
                    "ncells": ncells_here, "final_time": final_time,
                    "boundary_margin": margin, "degree": degree,
                    "steps": metadata["steps"],
                    "beta_hat_deg": measured["beta_hat_deg"],
                    "beta_dev_pct": (None if measured["beta_error_deg"] is None
                                     else 100.0 * measured["beta_error_deg"] / beta_exact),
                    "beta_hat_centroid_deg": centroid["beta_hat_centroid_deg"],
                    "beta_dev_centroid_pct": (
                        None if centroid["beta_error_centroid_deg"] is None
                        else 100.0 * centroid["beta_error_centroid_deg"] / beta_exact),
                    "rho_dev_pct": 100.0 * measured["rho_ratio_error"],
                    "p_dev_pct": 100.0 * measured["p_ratio_error"],
                    "preserve_l1": measured["preserve_l1"],
                    "centroid_scatter_deg": centroid["centroid_scatter_deg"],
                })
            print(f"[diag M{mach:g} th{theta_deg:g} P{degree} N{ncells_here} "
                  f"t={final_time}] centroid_dev="
                  f"{_pct(runs[-1]['beta_dev_centroid_pct'])} crossing_dev="
                  f"{_pct(runs[-1]['beta_dev_pct'])} preserve="
                  f"{runs[-1]['preserve_l1']:.4f} wall={time.time()-started:.1f}s",
                  flush=True)
    payload = {
        "study": "shallow-angle attribution",
        "mach": mach, "theta_deg": theta_deg, "degree": degree,
        "beta_exact_deg": beta_exact,
        "runs": runs,
        "interpretation": _interpret_shallow(runs),
    }
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    name = f"diagnose_M{mach:g}_th{theta_deg:g}_P{degree}.json"
    with open(output_dir / name, "w") as handle:
        json.dump(payload, handle, indent=2)
    return payload


def _interpret_shallow(runs):
    """Read the knob responses back into a one-line attribution."""
    coarse = [r for r in runs if r["ncells"] == min(x["ncells"] for x in runs)]
    base_margin = min(r["boundary_margin"] for r in coarse)
    base = [r for r in coarse if r["boundary_margin"] == base_margin]
    base.sort(key=lambda r: r["final_time"])
    key = "beta_dev_centroid_pct"
    base = [r for r in base if r.get(key) is not None]
    grows = (base[-1][key] or 0.0) > 2.0 * (base[0][key] or 1e-9)
    finer = [r for r in runs if r["ncells"] > min(x["ncells"] for x in runs)]
    finer = [r for r in finer if r.get(key) is not None]
    improves = (finer and base and (finer[-1][key] or 1e9)
                < 0.5 * (base[-1][key] or 1e9))
    wide = [r for r in coarse if r["boundary_margin"] > base_margin]
    wide = [r for r in wide if r.get(key) is not None]
    margin_helps = (wide and base
                    and (wide[-1][key] or 1e9) < 0.5 * (base[-1][key] or 1e9))
    parts = []
    if grows:
        parts.append("deviation grows with time -> the numerical field drifts, "
                     "it is not only a measurement artefact")
    else:
        parts.append("deviation is flat in time -> the error is set by the "
                     "projected initial data (front smearing across cells)")
    parts.append("finer mesh reduces the deviation" if improves
                 else "finer mesh does not remove the deviation")
    parts.append("excluding a wider band near the boundaries removes it "
                 "(boundary-driven)" if margin_helps
                 else "excluding a wider band near the boundaries does not "
                      "remove it (whole-domain effect)")
    return "; ".join(parts)



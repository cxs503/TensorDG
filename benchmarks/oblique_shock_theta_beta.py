"""theta--beta--Mach anchor set + (M, theta, p) oblique-shock case matrix for DG.

Mission m15977 (paper line: ``dg-oblique-shock-theta-beta``).

What this module adds on top of :mod:`benchmarks.oblique_shock`
---------------------------------------------------------------
``benchmarks.oblique_shock`` already contains the weak-branch algebra, an exact
two-state initial condition and a measurement harness.  It has **one** branch
(``beta_from_theta`` picks the first root, i.e. the weak solution) and it does
not publish a machine-readable anchor file.  This module adds

* the **strong** branch (``beta_from_theta_branch``) and the detachment point
  ``(theta_max, beta_detached)`` as first-class, refined quantities;
* ``theta_beta_anchors.json`` -- the anchor artifact ``AN-THETA-BETA-MACH``:
  every (M, theta) pair on both branches with the Rankine--Hugoniot jump
  values, the RH residual and the declared **limit checks** (``theta = 0``
  degeneracy, ``theta_max(M)`` merge, branch continuity, normal-shock limit);
* ``case_matrix.csv`` -- the DG verification matrix (>= 5 Mach x >= 4 theta x
  p = 1, 2), one row per run, with the recovered shock angle, the recovered
  jumps and the deviations from the anchor values;
* ``convergence.json`` -- three-level grid refinement (Roache GCI) on the shock
  angle and on the jump ratios;
* strong-branch runs that fail to hold the exact solution are recorded with an
  attribution instead of being dropped.

Anchors are generated by this module (no number is typed by hand); the closure
is the classic compressible-flow algebra (Anderson, *Modern Compressible Flow*,
3rd ed., ch. 4; normal-shock ratios in ch. 3), which the limit checks exercise
independently of the DG solver.

Branches
--------
For ``theta < theta_max(M)`` the relation ``theta(beta)`` has two roots.  The
weak root is the physically selected one in a wedge flow; the strong root
requires a downstream back pressure to be sustained and is *non-unique* in a
free outflow -- that is exactly what the strong-branch runs test.
"""

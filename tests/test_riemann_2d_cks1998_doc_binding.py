"""Bind ``docs/CASE-DG-CKS1998-2D-RIEMANN.md`` to its machine record and to the solver.

Why this test exists
--------------------
The case document, the record it calls its source of truth
(``docs/benchmarks/results/riemann_2d_cks1998/metrics.json``) and the driver that
regenerates that record had silently drifted apart:

* the document quoted a transmissive mass change of ``0.3494`` (~52 %) and
  extrema ``rho_max=1.571`` / ``p_max=1.622``, while the committed record said
  ``0.0828`` / ``1.569`` / ``1.619`` at 16x16, ``t=0.1``, ``CFL=0.1``;
* the documented reproduce command ``python -m benchmarks.riemann_2d_cks1998
  --quick`` had meanwhile moved to 32x32, ``t=0.25``, ``CFL=0.2``, so running it
  overwrote the record with numbers no line of the document mentioned;
* nothing failed, because every number in the document was typed by hand and no
  test compared the document to the record.

This module closes the triangle at the precision the document prints:

1. **Record -> scoring.**  ``judge(record["runs"])`` must reproduce the committed
   ``verdicts`` exactly.  A stale verdict block (numbers from an older code
   version next to newer rows) fails here; so does a verdict that was typed in.
2. **Record -> a-priori bounds.**  Every ``c6_bounds`` entry must equal
   ``a_priori_bounds(final_time)``, which reads the four initial Riemann states
   and the geometry only.  A bound fitted to the run fails here.
3. **Record -> document.**  The document's ``DOC-NUMBERS`` block must equal
   ``render_doc_numbers_block(record)`` byte for byte, and the reproduce command
   the record declares must be the command the document shows.  Hand edits and
   records regenerated at another configuration both fail here.
4. **Record -> figure.**  The declared figure exists, is a real PNG, and is drawn
   from the row the record declares (``provenance.figure_source_row``) -- the
   driver plots an already-measured row instead of re-solving for the picture.
5. **Solver -> record shape.**  One cheap run goes through the same ``judge`` and
   must satisfy the gates it can satisfy at that size, so the record's gate
   vocabulary is not decoupled from the solver.

Limitations: the *full* profile stores only cell averages, not the full fields,
so leg 1 can only be exercised on the ``quick`` profile record (the committed
one).  Python-level reproduction of the 32x32 record itself is not attempted here
because it costs minutes per solve; the record is regenerated by the command it
declares.

Run: ``python -m pytest tests/test_riemann_2d_cks1998_doc_binding.py -q``
"""
from __future__ import annotations

import json
import pathlib
import struct

import pytest

from benchmarks.riemann_2d_cks1998 import (
    QUICK_CONFIG,
    a_priori_bounds,
    judge,
    render_doc_numbers_block,
    run_riemann_2d,
)

ROOT = pathlib.Path(__file__).resolve().parents[1]
DOC_PATH = ROOT / "docs" / "CASE-DG-CKS1998-2D-RIEMANN.md"
RESULTS_DIR = ROOT / "docs" / "benchmarks" / "results" / "riemann_2d_cks1998"
RECORD_PATH = RESULTS_DIR / "metrics.json"

REL_TOL = 1e-12
BOUND_FIELDS = (
    "mass0",
    "rho_max0",
    "p_max0",
    "speed_max0",
    "perimeter",
    "mass_flux_bound",
    "rho_cap",
    "p_cap",
)


@pytest.fixture(scope="module")
def record() -> dict:
    assert RECORD_PATH.exists(), f"missing machine record {RECORD_PATH}"
    return json.loads(RECORD_PATH.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def doc() -> str:
    assert DOC_PATH.exists(), f"missing case document {DOC_PATH}"
    return DOC_PATH.read_text(encoding="utf-8")


# ---------------------------------------------------------------------------
# 1. Record -> scoring
# ---------------------------------------------------------------------------

def test_verdicts_follow_from_recorded_rows(record):
    """The verdict block must be recomputable from the rows in the same file."""
    if record["profile"] != "quick":
        pytest.skip(
            "only the quick profile stores enough per-row data to rescore C1/C4/C5/C6 "
            "without re-running the convergence meshes"
        )
    rescored = judge(record["runs"], convergence=None)
    assert set(rescored) == set(record["verdicts"]), (
        "record verdicts and judge() disagree about which gates exist: "
        f"{sorted(set(rescored) ^ set(record['verdicts']))}"
    )
    for gate, expected in rescored.items():
        committed = record["verdicts"][gate]
        for key, value in expected.items():
            assert key in committed, f"{gate}: record is missing '{key}'"
            if isinstance(value, float):
                assert committed[key] == pytest.approx(value, rel=1e-12, abs=0.0), (
                    f"{gate}.{key}: record says {committed[key]!r}, rows imply {value!r}; "
                    "the verdict block is stale with respect to the rows"
                )
            else:
                assert committed[key] == value, (
                    f"{gate}.{key}: record says {committed[key]!r}, rows imply {value!r}"
                )


# ---------------------------------------------------------------------------
# 2. Record -> a-priori bounds (initial data only)
# ---------------------------------------------------------------------------

def test_c6_bounds_are_initial_data_only(record):
    """Every stored C6 bound must be reproducible without looking at a solution."""
    assert record["runs"], "record has no rows"
    for index, row in enumerate(record["runs"]):
        expected = a_priori_bounds(row["final_time"])
        stored = row["c6_bounds"]
        for name in BOUND_FIELDS:
            assert name in stored, f"runs[{index}].c6_bounds is missing '{name}'"
            assert stored[name] == pytest.approx(expected[name], rel=REL_TOL, abs=0.0), (
                f"runs[{index}].c6_bounds[{name}]: stored {stored[name]!r}, "
                f"initial data implies {expected[name]!r}"
            )
        assert row["initial_mass"] == pytest.approx(expected["mass0"], rel=REL_TOL), (
            f"runs[{index}].initial_mass does not match the analytic quadrant mass"
        )


def test_periodic_control_conserves_mass(record):
    """The periodic control row exists and its mass drift is the C5 number."""
    periodic = [r for r in record["runs"] if tuple(r["periodic"]) == (True, True)]
    assert len(periodic) == 1, "record must carry exactly one periodic control row"
    row = periodic[0]
    drift = abs(row["total_mass"] - row["initial_mass"]) / abs(row["initial_mass"])
    assert drift < record["gates"]["C5_periodic_drift_rel"], (
        f"periodic mass drift {drift:.3e} exceeds the declared C5 tolerance"
    )
    assert record["verdicts"]["C5_periodic_drift"]["passed"] is True


# ---------------------------------------------------------------------------
# 3. Record -> document (byte-for-byte on the rendered block)
# ---------------------------------------------------------------------------

def test_document_number_block_is_rendered_from_record(record, doc):
    expected = render_doc_numbers_block(record)
    assert expected in doc, (
        "the DOC-NUMBERS block in docs/CASE-DG-CKS1998-2D-RIEMANN.md is not the one "
        "rendered from metrics.json. Regenerate it with:\n"
        "  python -m benchmarks.riemann_2d_cks1998 --quick --sync-doc\n"
        f"expected block:\n{expected}"
    )


def test_documented_reproduce_command_matches_record(record, doc):
    command = record["provenance"]["command"]
    assert command in doc, (
        f"the document does not show the command the record was produced by ({command!r})"
    )
    if record["profile"] == "quick":
        config = record["provenance"]["quick_config"]
        first = record["runs"][0]
        for key in ("ncells", "degree", "cfl"):
            assert config[key] == first[key], (
                f"provenance.quick_config[{key}]={config[key]!r} but runs[0].{key}="
                f"{first[key]!r}"
            )
        assert config["final_time"] == pytest.approx(first["final_time"])
    assert record["provenance"]["quick_config"] == QUICK_CONFIG, (
        "the quick profile changed since the record was produced; regenerate it with "
        "`python -m benchmarks.riemann_2d_cks1998 --quick --sync-doc`"
    )


def test_document_states_no_number_outside_the_block(record, doc):
    """Retired hand-typed figures must not come back into the prose."""
    retired = ("0.3494", "1.571", "1.622", "16×16, P1")
    for token in retired:
        assert token not in doc, (
            f"{token!r} is a hand-typed figure that no longer follows from "
            f"{RECORD_PATH.name}; quote the rendered block instead"
        )


# ---------------------------------------------------------------------------
# 4. Record -> figure
# ---------------------------------------------------------------------------

def _png_size(path: pathlib.Path) -> tuple[int, int]:
    header = path.read_bytes()[:24]
    assert header[:8] == b"\x89PNG\r\n\x1a\n", f"{path} is not a PNG"
    width, height = struct.unpack(">II", header[16:24])
    return width, height


def test_figure_is_declared_and_real(record, doc):
    provenance = record["provenance"]
    figure = RESULTS_DIR / provenance["figure"]
    assert figure.exists(), f"declared figure {figure} is missing"
    width, height = _png_size(figure)
    assert width >= 600 and height >= 300, f"{figure.name} looks degenerate ({width}x{height})"
    assert figure.stat().st_size > 10_000, f"{figure.name} is suspiciously small"
    assert provenance["figure"] in doc, "the document does not name the recorded figure"


def test_figure_comes_from_a_recorded_row(record):
    index = record["provenance"]["figure_source_row"]
    assert 0 <= index < len(record["runs"]), (
        f"figure_source_row={index} does not point at a stored row"
    )
    row = record["runs"][index]
    assert tuple(row["periodic"]) != (True, True), (
        "the density figure must come from the physical (transmissive) row"
    )
    assert f"p{row['degree']}_{row['ncells']}.png" in record["provenance"]["figure"]


# ---------------------------------------------------------------------------
# 5. Solver -> record shape (cheap run through the same judge)
# ---------------------------------------------------------------------------

def test_cheap_solver_run_is_scorable_by_the_same_judge():
    """A few-second run must satisfy the gates that do not need a fine mesh."""
    row = run_riemann_2d(ncells=8, degree=1, final_time=0.05, cfl=0.2)
    verdicts = judge([row])
    assert row["steps"] > 0, "solver did not advance in time"
    assert verdicts["C1_positivity"]["passed"], (
        f"positivity failed on a cheap run: rho_min="
        f"{verdicts['C1_positivity']['worst_rho_min']!r}, "
        f"p_min={verdicts['C1_positivity']['worst_p_min']!r}"
    )
    assert verdicts["C3_finite"]["passed"], "cheap run produced NaN/Inf"
    assert verdicts["C4_flux_balance"]["passed"], (
        "discrete flux balance does not close on a cheap run: residual "
        f"{verdicts['C4_flux_balance']['worst_relative_residual']!r}"
    )
    assert verdicts["C6_physical_magnitude"]["passed"], (
        "cheap run left the a-priori magnitude bounds: "
        f"mass ratio {verdicts['C6_physical_magnitude']['worst_mass_bound_ratio']!r}, "
        f"extremum {verdicts['C6_physical_magnitude']['worst_extremum_factor']!r}"
    )
    assert verdicts["C2_self_convergence"]["check_state"] == "not_run", (
        "a single-mesh run must report C2 as NOT_RUN, never as PASS"
    )


# ---------------------------------------------------------------------------
# 0. Documented initial states are the solver's initial states (input binding)
# ---------------------------------------------------------------------------

_QUADRANT_KEYS = {
    "左下": "lower-left",
    "右下": "lower-right",
    "左上": "upper-left",
    "右上": "upper-right",
}


def test_documented_initial_states_match_solver(doc):
    """The quadrant table in §① must be the solver's own Lax-Liu config 3."""
    from tensordg.euler_dg_2d import LAX_LIU_CONFIG_3

    found = {}
    for line in doc.splitlines():
        if not line.strip().startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) != 6 or cells[0] not in _QUADRANT_KEYS:
            continue
        found[_QUADRANT_KEYS[cells[0]]] = [float(value) for value in cells[2:6]]

    assert set(found) == set(LAX_LIU_CONFIG_3), (
        "the document no longer tabulates all four Lax-Liu config-3 quadrants: "
        f"{sorted(found)}"
    )
    for quadrant, values in found.items():
        expected = LAX_LIU_CONFIG_3[quadrant]
        for got, want in zip(values, expected):
            assert got == pytest.approx(want, rel=1e-12, abs=0.0), (
                f"{quadrant}: document says {values}, solver says {expected}"
            )

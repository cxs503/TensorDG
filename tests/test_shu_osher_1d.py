"""Regression gates for the Shu--Osher shock / entropy-wave benchmark.

The expensive reference solution is committed as ``benchmarks/data/shu_osher_reference.npz``
(P3 / WENO / 300 cells / t = 1.8, generated by ``benchmarks/shu_osher_1d.py`` and
re-rendered by ``benchmarks/report_shu_osher.py``); the tests re-run only small
configurations that keep the suite cheap.  See ``docs/shu_osher_verification.md``.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest
import torch

from benchmarks.shu_osher_1d import (
    DIAPHRAGM,
    DOMAIN,
    LEFT,
    WAVE_WINDOW,
    density_error,
    initial_state,
    shock_position,
    solve_case,
    wave_metrics,
)

REFERENCE_PATH = Path("benchmarks/data/shu_osher_reference.npz")
PAIR_PATH = Path("benchmarks/data/shu_osher_coarse_pair.npz")
GATE = 0.03  # documented 3% error threshold


def load_reference():
    blob = np.load(REFERENCE_PATH, allow_pickle=False)
    return blob["x"], blob["rho"], json.loads(str(blob["meta"]))


def test_initial_data_matches_the_published_left_and_right_states():
    x = torch.tensor([-4.5, -4.001, -3.999, 0.0, 0.37], dtype=torch.float64)
    rho, u, p = initial_state(x)
    assert float(rho[0]) == pytest.approx(LEFT[0], rel=0, abs=1e-12)
    assert float(u[0]) == pytest.approx(LEFT[1], rel=0, abs=1e-12)
    assert float(p[0]) == pytest.approx(LEFT[2], rel=0, abs=1e-12)
    # the sine branch is evaluated exactly, not discretised
    for i in (2, 3, 4):
        assert float(rho[i]) == pytest.approx(1.0 + 0.2 * np.sin(5.0 * float(x[i])), abs=1e-12)
        assert float(u[i]) == pytest.approx(0.0, abs=1e-12)
        assert float(p[i]) == pytest.approx(1.0, abs=1e-12)
    # the jump sits on a cell face for any multiple-of-ten grid, never inside a cell
    assert DIAPHRAGM == DOMAIN[0] + 1.0
    assert (DOMAIN[1] - DIAPHRAGM) / (DOMAIN[1] - DOMAIN[0]) == pytest.approx(0.9)


def test_transmissive_boundary_leaves_a_uniform_stream_undisturbed():
    """The open boundary must not reflect: a uniform stream has to stay uniform."""
    def uniform(x):
        return torch.ones_like(x), torch.full_like(x, 0.5), torch.ones_like(x)
    x, coeff, meta = _solve_with(uniform, ncells=50, degree=2, final_time=0.05,
                                 boundary="transmissive")
    rho = coeff[:, 0, 0]
    assert meta["boundary"] == "transmissive"
    assert np.max(np.abs(rho - 1.0)) < 1e-12
    assert np.all(np.isfinite(coeff))


def test_boundary_argument_is_validated():
    with pytest.raises(ValueError):
        _solve_with(lambda x: (torch.ones_like(x), torch.zeros_like(x), torch.ones_like(x)),
                    ncells=30, degree=1, final_time=0.01, boundary="reflecting")


def _solve_with(state, ncells, degree, final_time, boundary):
    from tensordg.euler_dg_1d import solve_periodic_euler_dg_1d
    x, coeff, meta = solve_periodic_euler_dg_1d(
        state, ncells=ncells, degree=degree, final_time=final_time, domain=DOMAIN,
        limiter=None, boundary=boundary,
    )
    return x.numpy(), coeff.numpy(), meta


def test_committed_reference_is_admissible_and_resolved():
    x, rho, meta = load_reference()
    assert meta["ncells"] == rho.size == x.size
    assert meta["degree"] == 3 and meta["limiter"] == "weno"
    assert np.all(np.isfinite(rho)) and rho.min() > 0.0
    # documented values of the reference profile (docs/shu_osher_verification.md)
    assert rho.max() == pytest.approx(4.221, abs=5e-3)
    assert rho.min() == pytest.approx(0.800, abs=5e-3)
    assert wave_metrics(x, rho)["n_local_extrema"] >= 10
    assert shock_position(x, rho) == pytest.approx(2.404, abs=5e-3)
    # the far field is still essentially at rest; the residual 1.8% deviation is a
    # known smooth-region perturbation of the limiter (see the report, section 5)
    assert abs(rho[x > 4.4].max() - 1.0) < 0.05


def load_pair():
    """Pinned P2 / 150-cell profiles (no limiter vs WENO) produced by the benchmark."""
    blob = np.load(PAIR_PATH, allow_pickle=False)
    meta = json.loads(str(blob["meta"]))
    return meta, {lim: (blob[f"x_{lim}"], blob[f"rho_{lim}"]) for lim in ("none", "weno")}


def test_limited_coarse_run_stays_within_the_three_percent_gate():
    x_ref, rho_ref, _ = load_reference()
    meta, pair = load_pair()
    x, rho = pair["weno"]
    factor = rho_ref.size // rho.size
    assert factor * rho.size == rho_ref.size
    error = density_error(rho, rho_ref, factor)
    assert error["relative_l1"] < GATE, error
    assert error["relative_l2"] < GATE, error
    assert np.all(np.isfinite(rho)) and rho.min() > 0.0


def test_unlimited_high_order_run_overshoots_the_shock_more_than_the_limited_one():
    _, rho_ref, _ = load_reference()
    meta, pair = load_pair()
    x_none, rho_none = pair["none"]
    x_weno, rho_weno = pair["weno"]
    assert rho_none.max() > rho_weno.max() + 0.2, (rho_none.max(), rho_weno.max())
    assert abs(rho_weno.max() - rho_ref.max()) < abs(rho_none.max() - rho_ref.max())
    tv_none = wave_metrics(x_none, rho_none)["total_variation"]
    tv_weno = wave_metrics(x_weno, rho_weno)["total_variation"]
    assert tv_none > 1.2 * tv_weno, (tv_none, tv_weno)
    assert np.all(np.isfinite(rho_none)) and rho_none.min() > 0.0


def test_short_early_window_stays_physical_with_and_without_limiter():
    """Solver-level smoke test: a short run of the real case must stay admissible."""
    for limiter in (None, "weno"):
        x, avg, meta = solve_case(50, 1, limiter, cfl=0.3, final_time=0.15)
        rho = avg[:, 0]
        assert meta["boundary"] == "transmissive"
        assert np.all(np.isfinite(avg))
        assert rho.min() > 0.0
        assert rho.max() < 4.0 + 0.5


def test_shock_position_ignores_the_left_state_above_the_threshold():
    """The left state (rho = 3.857) is above the crossing level, so the scan must be reversed."""
    x = np.linspace(0.0, 1.0, 11)
    rho = np.where(x < 0.3, 3.857143, 1.0)
    rho[6:] = 3.857143
    rho[8:] = 1.0
    assert shock_position(x, rho, level=2.0) == pytest.approx(0.765, abs=1e-6)


def test_wave_window_metrics_on_a_synthetic_profile():
    x = np.linspace(0.0, 5.0, 501)
    rho = 4.0 + np.sin(4.0 * x)
    metrics = wave_metrics(x, rho, window=(0.0, 4.2))
    assert metrics["n_local_extrema"] >= 4
    assert metrics["wave_amplitude"] == pytest.approx(
        float(np.ptp(rho[(x >= 0.0) & (x <= WAVE_WINDOW[1])])), rel=1e-12)
    assert metrics["total_variation"] > 0.0
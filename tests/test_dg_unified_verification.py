def _load_run() -> dict:
    assert RUN_JSON.is_file(), f"missing run artifact {RUN_JSON}"
    with open(RUN_JSON) as handle:
        return json.load(handle)


def test_artifacts_contract():
    run = _load_run()
    gates = run["gates"]
    assert set(gates) == {"E1_rotation_l2", "E2_deformation_l2", "E3_dispersion",
                          "E4_soliton_l2", "E5_mass_drift"}
    for name, gate in gates.items():
        # the verdict must be re-derivable from the record itself
        assert gate["pass"] == (gate["value"] <= gate["limit"]), name
        assert math.isfinite(gate["value"])
    # limits recorded in the artifact must be the campaign limits
    assert gates["E1_rotation_l2"]["limit"] == CAMPAIGN_LIMITS["E1"]
    assert gates["E2_deformation_l2"]["limit"] == CAMPAIGN_LIMITS["E2"]
    assert gates["E3_dispersion"]["limit"] == CAMPAIGN_LIMITS["E3"]
    assert gates["E4_soliton_l2"]["limit"] == CAMPAIGN_LIMITS["E4"]
    assert gates["E5_mass_drift"]["limit"] == CAMPAIGN_LIMITS["E5"]
    # provenance and figures must be present and on disk
    assert run["environment"]["torch"] and run["environment"]["numpy"]
    assert len(run.get("figures", [])) >= 4
    for rel in run["figures"]:
        assert (RESULT_DIR / rel).is_file(), rel
    # determinism claim: no random seeds used anywhere
    assert "deterministic" in run["seeds"]


def test_evidence_pointers_resolve():
    assert EVIDENCE_JSON.is_file(), f"missing evidence bundle {EVIDENCE_JSON}"
    with open(EVIDENCE_JSON) as handle:
        evidence = json.load(handle)
    for key in ("impl_files", "entry", "run_artifacts", "integration_callers",
                "benchmark", "repro_cmd", "external_anchor"):
        assert evidence.get(key), f"empty evidence key {key}"
    assert evidence_mod.verify(str(EVIDENCE_JSON), base_dir=str(REPO)) == []
    for rel in evidence["impl_files"] + evidence["entry"] + evidence["run_artifacts"]:
        assert (REPO / rel).is_file(), rel


def test_evidence_benchmark_matches_run_artifact():
    with open(EVIDENCE_JSON) as handle:
        evidence = json.load(handle)
    run = _load_run()
    derived = evidence_mod.build_benchmark_table(run)
    for cid, row in evidence["benchmark"].items():
        assert row["got"] == pytest.approx(derived[cid]["got"], rel=0, abs=0)
        assert row["tolerance"] == derived[cid]["tolerance"]
        assert row["pass"] == derived[cid]["pass"]
        assert row["error"] == pytest.approx(row["got"], rel=0, abs=0)
    # E3 must publish the whole sampled band, not only the maximum
    assert len(evidence["benchmark"]["E3"]["reference_values"]) >= 5


def test_evidence_tamper_is_detected(tmp_path):
    """Negative control: a doctored number must be rejected by ``verify``."""
    with open(EVIDENCE_JSON) as handle:
        evidence = json.load(handle)
    clean = tmp_path / "clean.json"
    with open(clean, "w") as handle:
        json.dump(evidence, handle)
    assert evidence_mod.verify(str(clean), base_dir=str(REPO)) == []

    tampered = json.loads(json.dumps(evidence))
    tampered["benchmark"]["E1"]["got"] = 0.0          # pretend a perfect solver
    tampered["benchmark"]["E1"]["error"] = 0.0
    bad = tmp_path / "tampered.json"
    with open(bad, "w") as handle:
        json.dump(tampered, handle)
    problems = evidence_mod.verify(str(bad), base_dir=str(REPO))
    assert any("benchmark E1.got" in p for p in problems), problems


def test_gate_values_reproduce_across_independent_runs():
    """A deterministic surface must reproduce a previous run bit for bit.

    ``prior_run_gates.json`` holds the gate values of an earlier independent run
    (same declared configurations, different process); the surface uses no random
    numbers, so any difference means a hidden non-deterministic code path.
    """
    prior_path = RESULT_DIR / "prior_run_gates.json"
    assert prior_path.is_file(), f"missing {prior_path}"
    prior = json.loads(prior_path.read_text())
    run = _load_run()
    assert len(prior["source_commit"]) == 40
    for name, gate in run["gates"].items():
        assert prior["gates"][name]["value"] == gate["value"], name
        assert prior["gates"][name]["pass"] is True
    with open(EVIDENCE_JSON) as handle:
        evidence = json.load(handle)
    assert evidence["reproducibility"]["gate_values_identical"] is True
    assert evidence["reproducibility"]["prior_run_source_commit"] == prior["source_commit"]


def test_entry_point_writes_artifacts_quick(tmp_path, monkeypatch):
    """The package entry must serialise the registry result without hand edits."""
    from benchmarks.dg import __main__ as entry

    def fake_surface(mode="declared"):
        crit = {}
        for cid, limit in CAMPAIGN_LIMITS.items():
            crit[cid] = {"id": cid, "physics": f"stub {cid}", "metric": "stub",
                         "reference": f"stub reference {cid}",
                         "got": 0.5 * limit, "tolerance": limit,
                         "pass": True, "detail": {}}
        return {"mode": mode, "criteria": crit, "verdict": "PASS", "wall_seconds": 0.0}

    monkeypatch.setattr(surface, "run_surface", fake_surface)
    rc = entry.main(["--quick", "--outdir", str(tmp_path)])
    assert rc == 0
    payload = json.loads((tmp_path / "dg_surface_quick.json").read_text())
    assert payload["verdict"] == "PASS"
    assert set(payload["benchmark"]) == set(CAMPAIGN_LIMITS)
    assert payload["apriori_limits"] == CAMPAIGN_LIMITS
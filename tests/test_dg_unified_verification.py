def test_registry_matches_campaign_criteria():
    """The registry must encode exactly the five campaign limits and nothing else."""
    assert set(surface.CRITERIA) == set(CAMPAIGN_LIMITS) == set(surface.TOLERANCES)
    for cid, limit in CAMPAIGN_LIMITS.items():
        assert surface.TOLERANCES[cid] == limit, f"{cid} limit drifted"
        spec = surface.CRITERIA[cid]
        for key in ("physics", "metric", "reference", "module", "declared", "quick"):
            assert spec.get(key), f"{cid} missing {key}"
        assert spec["module"] in {"tensordg.advection_diffusion", "tensordg.dispersive"}
        # the morphologies the campaign asked for must actually be reachable
    assert "rotation" in surface.CRITERIA["E1"]["physics"]
    assert "LeVeque" in surface.CRITERIA["E2"]["physics"]
    assert "tanh(kh)" in surface.CRITERIA["E3"]["reference"]
    assert "sech^2" in surface.CRITERIA["E4"]["physics"]


def test_rotation_reference_is_independent_of_solver():
    """Rebuild the exact quarter-revolution field with numpy, without the module.

    ``u(x, T/4)`` for rigid rotation is the *same* cosine bell translated to
    ``(1/4, 1/2)`` on the unit square: the rotation by -pi/2 maps the initial
    centre ``(1/2, 3/4)`` there.  Comparing the module's analytic reference with
    this numpy construction checks the reference, not the solver.
    """
    from tensordg.advection_diffusion import cosine_bell, rotated_field

    omega = 2.0 * math.pi
    quarter = 0.25 * 2.0 * math.pi / omega
    reference = rotated_field(cosine_bell(center=(0.5, 0.75), radius=0.15), omega, quarter)

    x = np.linspace(0.0, 1.0, 101)
    y = np.linspace(0.0, 1.0, 101)
    xx, yy = np.meshgrid(x, y, indexing="ij")
    r = np.sqrt((xx - 0.25) ** 2 + (yy - 0.5) ** 2)
    expected = np.where(r < 0.15, 0.5 * (1.0 + np.cos(np.pi * r / 0.15)), 0.0)

    got = reference(torch.as_tensor(xx), torch.as_tensor(yy)).numpy()
    assert np.max(np.abs(got - expected)) < 1e-12

    # negative control: a half-rotation moves the bell to (1/2, 1/4)-symmetric
    # position, so the quarter-turn reference cannot be the initial field
    initial = cosine_bell(center=(0.5, 0.75), radius=0.15)(
        torch.as_tensor(xx), torch.as_tensor(yy)).numpy()
    assert np.max(np.abs(got - initial)) > 0.9


def test_dispersion_reference_is_closed_form():
    """Airy dispersion must be the textbook expression, and the criterion discriminating."""
    from tensordg import dispersive as ds

    g, h = 9.80665, 1.0
    kh = np.array([0.1, 0.5, 1.0, 2.0, 3.5, 5.0])
    k = kh / h
    closed = np.sqrt(g * k * np.tanh(k * h))
    got = ds.airy_omega(torch.as_tensor(k), h, g).numpy()
    assert np.max(np.abs(got / closed - 1.0)) < 1e-14

    # the inherited operator symbol must reproduce omega^2 = g k tanh(kh)
    symbol = ds.dispersion_omega_sq(torch.as_tensor(k), h, g, model="airy").numpy()
    assert np.max(np.abs(symbol / closed ** 2 - 1.0)) < 1e-14

    # negative control: the classical Boussinesq reduction *must* break down at
    # kh = 5, otherwise the 3 % criterion would be vacuous
    bouss = ds.dispersion_omega_sq(torch.as_tensor(k), h, g,
                                   model="boussinesq").numpy()
    rel = np.abs(np.sqrt(bouss) / closed - 1.0)
    assert rel[-1] > 0.03



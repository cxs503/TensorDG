"""Acceptance gates for the DG unified verification surface (campaign P165W3-N05).

Two layers, so that a passing suite cannot be produced by editing prose:

**criteria** -- the four physics criteria plus the conservation criterion are
re-evaluated from fresh solver runs through the same registry the report and the
CI step use (:mod:`benchmarks.dg`), and the two references the criteria rely on
(analytic rotated bell, closed-form Airy dispersion) are rebuilt *independently*
of the code under test (numpy closed form, not the module's own helper).

**artifact contract** -- the committed run artifact and the evidence bundle are
audited: every gate must carry its measured value *and* its pre-declared limit
and the ``pass`` flag must equal ``value <= limit`` (a hand-edited verdict
fails); every evidence pointer must resolve; every benchmark number must equal
the run artifact's number; every declared tolerance must equal the registry's.
The tamper test is the negative control for that check.

Runtime: ~60 s (the declared 24-cell rotation run dominates).  The expensive
report run -- full mesh studies, figures, report.md -- is *not* repeated here;
it is regenerated by ``python -m benchmarks.dg``.
"""

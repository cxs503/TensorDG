"""Guard for the evidence-integrity contract (cheap: pure file/metadata reads).

Three properties are pinned, none of which a solver test can see:

1. **No orphan evidence.**  Every ``*.json`` under ``validation/``,
   ``artifacts/`` and ``docs/benchmarks/results`` must be read by some test,
   tool, benchmark or document.  Known archival exceptions live in
   ``validation/evidence_registry.json`` with a reason; a *new* unreferenced
   file fails here.  The engine is ``tools/audit_evidence_integrity.py``.
2. **The registry cannot rot.**  Every registered row must still exist on disk,
   and it must still be classified as an orphan (no laundering: registering a
   file must not make it "referenced").
3. **A refreshed artifact stays bound to its claim.**  The Ritter dry-bed
   number in ``validation/swe_dam_break/metrics.json`` -- the artifact the
   report calls the single source of truth -- must keep its provenance block,
   must stay in the 3 % band, must keep the retired 28.5 % value as an explicit
   ``legacy_pre_dry_guard`` record, and must still agree with the number quoted
   in ``docs/swe_verification.md``.  Before m14698 that artifact carried the
   *pre-dry-guard* value (28.546 %) as if it were current, i.e. the document and
   its declared source of truth disagreed by a factor of ~119 and nothing
   failed.
"""
from __future__ import annotations

import json
import os
import re

import pytest

from tools import audit_evidence_integrity as audit

REPO_ROOT = audit.REPO_ROOT
DAM_BREAK = os.path.join(REPO_ROOT, "validation", "swe_dam_break", "metrics.json")
DOC = os.path.join(REPO_ROOT, "docs", "swe_verification.md")


@pytest.fixture(scope="module")
def audit_result():
    return audit.audit()


@pytest.fixture(scope="module")
def registry():
    return audit.load_registry()


def test_no_unregistered_orphan_evidence(audit_result, registry):
    unknown = audit.new_orphans(audit_result, registry)
    assert not unknown, (
        "new evidence artifacts are read by nothing (add a consumer or register "
        f"them in validation/evidence_registry.json): {unknown}")


def test_registry_rows_are_alive_and_still_orphans(audit_result, registry):
    assert not audit.stale_registry_entries(registry), \
        "registry rows whose artifact disappeared (ratchet rot)"
    orphans = set(audit_result["orphans"])
    for path, meta in (registry.get("orphans") or {}).items():
        assert path in orphans, (
            f"{path} is registered as an orphan but the audit now classifies it as "
            "referenced -- either it gained a consumer (drop the row) or the "
            "registry itself is being scanned as a consumer")
        assert meta.get("reason"), f"{path}: registry row without a reason"
        assert meta.get("status") in {"archival", "candidate_retirement", "needs_review"}


def test_audit_does_not_launder_its_own_outputs():
    for path in ("validation/evidence_registry.json",
                 "artifacts/evidence_integrity_audit.json",
                 "docs/evidence_integrity_audit.md"):
        assert path in audit.SELF_OUTPUTS
        assert os.path.abspath(os.path.join(REPO_ROOT, path)) != REPO_ROOT


def test_every_registered_orphan_is_reported_in_the_machine_report(audit_result, registry):
    report = os.path.join(REPO_ROOT, "artifacts", "evidence_integrity_audit.json")
    if not os.path.exists(report):  # pragma: no cover - regenerated by the tool
        pytest.skip("run tools/audit_evidence_integrity.py --write")
    payload = json.load(open(report))
    reported = {entry["path"] for entry in payload["artifacts"]}
    assert set(registry.get("orphans") or {}) <= reported


# ---------------------------------------------------------------------------
# artifact <-> claim binding (the stale-evidence defect of m14698)
# ---------------------------------------------------------------------------

@pytest.fixture(scope="module")
def ritter_block():
    payload = json.load(open(DAM_BREAK))
    return payload, payload["ritter"]


def test_ritter_block_carries_provenance(ritter_block):
    payload, block = ritter_block
    prov = block.get("_provenance") or payload.get("provenance")
    assert prov, "the refreshed ritter block lost its provenance stamp"
    assert prov.get("block") == "ritter"
    assert prov.get("generator", "").endswith("validation/swe_dam_break/study.py")
    # a commit sha (possibly empty when git is unavailable) or an explicit reason
    assert re.fullmatch(r"[0-9a-f]{7,40}", prov.get("git_commit", "")), prov.get("git_commit")


def test_ritter_reaches_the_requested_time_and_the_three_percent_band(ritter_block):
    _, block = ritter_block
    assert block["time_reached"] == pytest.approx(block["final_time"], abs=1e-12), \
        "the dry-bed run must actually integrate to final_time (the retired defect)"
    assert block["rel_l1_h"] < 0.03, block["rel_l1_h"]
    assert block["rel_l1_h"] > 0.0


def test_retired_value_is_kept_as_an_explicit_legacy_record(ritter_block):
    _, block = ritter_block
    legacy = block.get("legacy_pre_dry_guard")
    assert legacy, "the pre-dry-guard 28.5 % value must stay documented, not deleted"
    assert legacy["rel_l1_h"] > 10.0 * block["rel_l1_h"]
    assert "dry" in legacy["retired_by"].lower()


def test_untouched_blocks_are_declared_not_remeasured(ritter_block):
    payload, _ = ritter_block
    declared = set(payload.get("blocks_not_remeasured_in_this_run") or [])
    assert declared, "a partial refresh must declare which blocks it did not remeasure"
    assert "ritter" not in declared
    # every remaining top-level numeric study block is either remeasured or declared
    for key in ("stoker", "lake_rest_1d", "lake_rest_2d"):
        if key in payload:
            assert key in declared, key


def test_document_agrees_with_its_declared_source_of_truth(ritter_block):
    _, block = ritter_block
    text = open(DOC).read()
    row = re.search(r"\|\s*relative L1 error of h\s*\|\s*([0-9.]+)\s*%\s*\|\s*([0-9.]+)\s*%", text)
    assert row, "the 'Old | New' table row disappeared from docs/swe_verification.md"
    old_pct, new_pct = float(row.group(1)), float(row.group(2))
    # the "Old" column is the retired defect, the "New" column is the current solver
    assert old_pct == pytest.approx(block["legacy_pre_dry_guard"]["rel_l1_h"] * 100.0,
                                    rel=0.01), (old_pct, block["legacy_pre_dry_guard"]["rel_l1_h"])
    assert new_pct == pytest.approx(block["rel_l1_h"] * 100.0, rel=0.10), (
        "docs/swe_verification.md quotes a value its declared source of truth does not "
        f"contain: doc={new_pct}% artifact={block['rel_l1_h'] * 100.0:.4f}%")
"""Systematic convergence / GCI verification for the TensorDG kernels.

Two layers are tested:

* **estimators** -- :mod:`tensordg.convergence` is checked against synthetic
  error series whose order and exact limit are known analytically, so a broken
  estimator cannot masquerade as a passing solver;
* **kernels** -- measured orders of the DG/SIPG solvers are asserted against the
  *theoretical* orders (``p + 1`` in L2 for SIPG/DG with smooth data), and the
  grid-convergence index is asserted to bracket the error against the analytic
  solution. No reference value in this file is generated by the solver under
  test: every reference is either an analytic formula or a Richardson/GCI
  estimate of the numerical series itself.
"""
import math

import pytest

import tensordg.heat_1d as heat_1d
from tensordg import (
    l2_error,
    poisson_error_2d,
    solve_advection,
    solve_heat_1d,
    solve_poisson_2d,
)
from tensordg.convergence import (
    DEFAULT_SAFETY_FACTOR,
    convergence_table,
    gci_study,
    modal_l2_norm_1d,
    modal_mean_2d,
    modal_point_value_2d,
    observed_order,
    p_decay_diagnostics,
    pairwise_orders,
    richardson_extrapolate,
)

# Analytic references (never produced by the discretisations under test).
POISSON_POINT_EXACT = 1.0  # sin(pi/2) * sin(pi/2)
POISSON_MEAN_EXACT = (2.0 / math.pi) ** 2
ADVECTION_NORM_EXACT = 1.0 / math.sqrt(2.0)  # ||sin(2*pi*(x - t))||_L2, independent of t


# ---------------------------------------------------------------------------
# Estimator layer: synthetic series with analytically known order / limit
# ---------------------------------------------------------------------------
def test_observed_order_recovers_known_synthetic_rates():
    resolutions = (4.0, 8.0, 16.0, 32.0)
    for order, coefficient in ((0.5, 3.0), (1.0, 0.7), (2.0, 0.25), (3.0, 0.1), (4.0, 0.05)):
        errors = [coefficient / n ** order for n in resolutions]
        estimate = observed_order(resolutions, errors)
        assert abs(estimate - order) < 1e-9, (order, estimate)
        for pair_order in pairwise_orders(resolutions, errors):
            assert abs(pair_order - order) < 1e-9


def test_convergence_table_flags_order_mismatch():
    resolutions = (8.0, 16.0, 32.0)
    errors = [0.5 / n ** 1.5 for n in resolutions]
    matching = convergence_table(resolutions, errors, theoretical_order=1.5)
    assert matching["order_within_tolerance"] is True
    assert abs(matching["order_deviation"]) < 1e-9
    mismatched = convergence_table(resolutions, errors, theoretical_order=2.0)
    assert mismatched["order_within_tolerance"] is False
    assert mismatched["order_deviation"] == pytest.approx(-0.5, abs=1e-9)


def test_richardson_and_gci_bracket_known_error():
    exact = 3.0
    coefficient, order, refinement = 0.7, 2.0, 2.0
    fine, medium, coarse = (
        exact + coefficient / n ** order for n in (32.0, 16.0, 8.0)
    )
    study = gci_study(fine, medium, coarse, refinement=refinement)
    actual_error = abs(fine - exact) / abs(exact) * 100.0
    assert study["order_observed"] == pytest.approx(order, abs=1e-6)
    assert study["in_asymptotic_range"] is True
    assert study["asymptotic_ratio"] == pytest.approx(1.0, abs=1e-3)
    # GCI must bracket the true discretisation error of the fine value.
    assert study["gci_fine_percent"] >= actual_error
    assert study["gci_fine_percent"] <= 1.5 * actual_error
    # Richardson extrapolation must be closer to the exact value than the fine sample.
    assert abs(study["extrapolated"] - exact) < abs(fine - exact)
    plain = richardson_extrapolate(fine, medium, refinement=refinement, order=order)
    assert plain == pytest.approx(exact, rel=1e-12)
    # The GCI must scale linearly with the safety factor.
    strict = gci_study(fine, medium, coarse, refinement=refinement, safety_factor=1.0)
    assert study["gci_fine_percent"] == pytest.approx(
        strict["gci_fine_percent"] * DEFAULT_SAFETY_FACTOR, rel=1e-12
    )


def test_gci_rejects_non_asymptotic_series():
    # Oscillating, non-converging triple: no positive order exists.
    study = gci_study(1.0, 1.02, 0.99, refinement=0.5)
    assert study["order_observed"] is None
    assert study["gci_fine_percent"] is None
    assert study["in_asymptotic_range"] is False


def test_p_decay_diagnostics_detects_spectral_and_failure():
    spectral = p_decay_diagnostics((0, 1, 2, 3), (1e-1, 1e-3, 1e-5, 1e-7))
    assert spectral["monotone_decreasing"] is True
    assert spectral["superlinear"] is True
    assert spectral["lsq_decay_rate"] == pytest.approx(math.log(100.0), rel=1e-9)
    stalled = p_decay_diagnostics((0, 1, 2), (1e-1, 9.9e-2, 1.2e-1))
    assert stalled["monotone_decreasing"] is False


# ---------------------------------------------------------------------------
# Kernel layer: SIPG Poisson (manufactured solution sin(pi x) sin(pi y))
# ---------------------------------------------------------------------------
def test_poisson_sipg_h_refinement_matches_theoretical_order():
    errors = []
    for cells in (4, 8, 16, 32):
        x, y, coeff, _ = solve_poisson_2d(ncells=cells, degree=1)
        errors.append(poisson_error_2d(x, y, coeff)["relative_l2"])
    table = convergence_table((4, 8, 16, 32), errors, theoretical_order=2.0)
    assert table["order_within_tolerance"], table
    assert all(1.8 <= rate <= 2.2 for rate in table["pairwise_orders"]), table

    for degree, theory in ((2, 3.0), (3, 4.0)):
        degree_errors = []
        for cells in (2, 4, 8):
            x, y, coeff, _ = solve_poisson_2d(ncells=cells, degree=degree)
            degree_errors.append(poisson_error_2d(x, y, coeff)["relative_l2"])
        degree_table = convergence_table((2, 4, 8), degree_errors, theoretical_order=theory)
        assert degree_table["order_within_tolerance"], degree_table
        assert all(
            abs(rate - theory) <= 0.25 for rate in degree_table["pairwise_orders"]
        ), degree_table


def test_poisson_gci_bounds_analytic_point_value_error():
    values = []
    for cells in (4, 8, 16):
        x, y, coeff, _ = solve_poisson_2d(ncells=cells, degree=1)
        values.append(modal_point_value_2d(x, y, coeff, 0.5, 0.5))
    study = gci_study(values[2], values[1], values[0], refinement=2.0)
    actual_error = abs(values[2] - POISSON_POINT_EXACT) / POISSON_POINT_EXACT * 100.0
    assert study["order_observed"] == pytest.approx(2.0, abs=0.15), study
    assert study["in_asymptotic_range"] is True, study
    assert study["gci_fine_percent"] >= actual_error, (study, actual_error)
    assert study["gci_fine_percent"] <= 2.0 * actual_error, (study, actual_error)
    # The mean functional is an independent (superconvergent) check with analytic value.
    assert abs(modal_mean_2d(solve_poisson_2d(ncells=16, degree=1)[2]) - POISSON_MEAN_EXACT) < 4e-3


def test_poisson_p_refinement_decays_superlinearly():
    errors = []
    for degree in (1, 2, 3):
        x, y, coeff, _ = solve_poisson_2d(ncells=8, degree=degree)
        errors.append(poisson_error_2d(x, y, coeff)["relative_l2"])
    diagnostics = p_decay_diagnostics((1, 2, 3), errors)
    assert diagnostics["monotone_decreasing"] is True
    assert diagnostics["superlinear"] is True
    assert diagnostics["lsq_decay_rate"] > 3.0
    assert errors[-1] < 1e-3 * errors[0]


# ---------------------------------------------------------------------------
# Kernel layer: periodic linear advection (exact translated sine)
# ---------------------------------------------------------------------------
def test_advection_h_refinement_and_gci_match_theory():
    errors, norms = [], []
    for cells in (10, 20, 40):
        centers, coeff, _ = solve_advection(ncells=cells, degree=2, final_time=0.25)
        errors.append(l2_error(centers, coeff, final_time=0.25))
        norms.append(modal_l2_norm_1d(centers, coeff))
    table = convergence_table((10, 20, 40), errors, theoretical_order=3.0)
    assert table["order_within_tolerance"], table
    assert all(2.8 <= rate <= 3.2 for rate in table["pairwise_orders"]), table
    # GCI on the solution L2 norm: the functional's exact value is analytic and
    # time independent, so the GCI can be compared with a true error.
    study = gci_study(norms[2], norms[1], norms[0], refinement=2.0)
    actual_error = abs(norms[2] - ADVECTION_NORM_EXACT) / ADVECTION_NORM_EXACT * 100.0
    assert study["in_asymptotic_range"] is True, study
    assert study["gci_fine_percent"] >= actual_error, (study, actual_error)
    assert study["gci_fine_percent"] <= 2.0 * actual_error, (study, actual_error)


def test_advection_p_refinement_is_exponential():
    errors = []
    for degree in (0, 1, 2, 3):
        centers, coeff, _ = solve_advection(ncells=32, degree=degree, final_time=0.25)
        errors.append(l2_error(centers, coeff, final_time=0.25))
    diagnostics = p_decay_diagnostics((0, 1, 2, 3), errors)
    assert diagnostics["monotone_decreasing"] is True
    assert diagnostics["superlinear"] is True
    # Each p step must cut the error by far more than the (p+1) h-refinement factor.
    assert min(diagnostics["reduction_factors"]) > 10.0, diagnostics
    assert errors[-1] / errors[0] < 1e-4


# ---------------------------------------------------------------------------
# Kernel layer: SIPG heat equation (exact sin(pi x) exp(-pi^2 t))
# ---------------------------------------------------------------------------
def test_heat_sipg_h_refinement_matches_theoretical_order():
    # dt is fixed explicitly so that the O(dt^2) Crank-Nicolson error stays well
    # below the spatial error and the observed order measures the SIPG space
    # discretisation (the default dt ~ 0.02 h would mask it with 2nd-order time
    # error for degree 2).
    for degree, theory in ((1, 2.0), (2, 3.0)):
        errors = []
        for cells in (8, 16, 32):
            centers, coeff, _ = solve_heat_1d(
                ncells=cells, degree=degree, final_time=0.1, time_steps=500
            )
            errors.append(heat_1d.heat_error(centers, coeff, 0.1)["relative_l2"])
        table = convergence_table((8, 16, 32), errors, theoretical_order=theory)
        assert table["order_within_tolerance"], (degree, table)
        assert all(
            abs(rate - theory) <= 0.15 for rate in table["pairwise_orders"]
        ), (degree, table)


# ---------------------------------------------------------------------------
# Cross-backend: matrix-free PCG must not degrade accuracy or order
# ---------------------------------------------------------------------------
def test_matrixfree_backend_preserves_dense_accuracy_and_order():
    x_dense, y_dense, coeff_dense, _ = solve_poisson_2d(ncells=8, degree=1, backend="dense")
    x_mf, y_mf, coeff_mf, meta = solve_poisson_2d(ncells=8, degree=1, backend="matrix-free")
    dense_error = poisson_error_2d(x_dense, y_dense, coeff_dense)["relative_l2"]
    mf_error = poisson_error_2d(x_mf, y_mf, coeff_mf)["relative_l2"]
    # An iterative solve may only differ from the direct one by round-off.
    assert abs(mf_error - dense_error) / dense_error < 1e-9, (dense_error, mf_error)
    assert meta["cg_residual_norm"] < 1e-9, meta
    assert meta["cg_iterations"] <= meta["dofs"], meta

    x4, y4, coeff4, _ = solve_poisson_2d(ncells=4, degree=1, backend="matrix-free")
    coarse_error = poisson_error_2d(x4, y4, coeff4)["relative_l2"]
    order = math.log(coarse_error / mf_error, 2)
    assert abs(order - 2.0) <= 0.1, order
    assert mf_error < 0.03
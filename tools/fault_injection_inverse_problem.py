"""Negative control for the differentiable-inverse-problem tutorial.

A verification suite is only worth its failures.  This tool injects four
realistic faults into :mod:`tensordg.differentiable` one at a time, runs
``tests/test_tutorial_inverse_problem.py``, records *which* assertions turn red,
and restores the file (``try``/``finally``, so an interrupted run still leaves a
clean tree).

The four faults are chosen to cover the fault classes that a parameter
identification workflow can suffer from:

====  =======================================================  =========================
id    fault                                                    first test that catches it
====  =======================================================  =========================
F1    positive-speed upwind interface flux flipped            continuum consistency
F2    ``speed.detach()`` inside the advection residual         gradient vs central diff.
F3    0.1 % time-step bookkeeping defect in ``advance_*``      matched-dt fit
F4    0.1 % diffusivity mis-scaling in ``advance_heat_1d``     continuum consistency
====  =======================================================  =========================

F1 and F4 are *invisible* to every self-consistent test (data generated by the
patched model is reproduced exactly by the patched model); they can only be
caught against the analytic solution.  That asymmetry is the point of the
tutorial and the reason the consistency study exists.

Usage::

    python tools/fault_injection_inverse_problem.py            # patch/run/restore
    python tools/fault_injection_inverse_problem.py --dry-run  # list the faults
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DIFFUSION_FILE = REPO / "tensordg" / "differentiable.py"
TEST_FILE = "tests/test_tutorial_inverse_problem.py"
OUT = REPO / "validation" / "inverse_problem"

FAULTS = [
    {
        "id": "F1",
        "description": "flip the positive-speed upwind interface flux in `_advection_rhs`",
        "old": "    flux_right = torch.where(positive, right_trace, torch.roll(left_trace, -1, dims=0))",
        "new": "    flux_right = torch.where(positive, torch.roll(left_trace, -1, dims=0), right_trace)",
        "class": "forward physics (hyperbolic)",
    },
    {
        "id": "F2",
        "description": "detach the differentiable speed inside `_advection_rhs`",
        "old": (
            "    if not torch.is_tensor(speed):\n"
            "        speed = torch.as_tensor(speed, dtype=coeff.dtype, device=coeff.device)\n"
            "    right_trace"
        ),
        "new": (
            "    if not torch.is_tensor(speed):\n"
            "        speed = torch.as_tensor(speed, dtype=coeff.dtype, device=coeff.device)\n"
            "    speed = speed.detach()\n"
            "    right_trace"
        ),
        "class": "gradient graph",
    },
    {
        "id": "F3",
        "description": "0.1 % time-step bookkeeping defect in `advance_advection_1d`",
        "old": "    for step in _step_sizes(dt, nsteps):\n        k1 = _advection_rhs(coeff, *arg)",
        "new": "    for step in _step_sizes(dt, nsteps):\n        step = 1.001 * step\n        k1 = _advection_rhs(coeff, *arg)",
        "class": "step-size bookkeeping",
    },
    {
        "id": "F4",
        "description": "0.1 % diffusivity mis-scaling in `advance_heat_1d`",
        "old": (
            "        system = mass_matrix + (0.5 * step * alpha_t) * diffusion\n"
            "        explicit = mass_matrix - (0.5 * step * alpha_t) * diffusion"
        ),
        "new": (
            "        scaled_alpha = 1.001 * alpha_t\n"
            "        system = mass_matrix + (0.5 * step * scaled_alpha) * diffusion\n"
            "        explicit = mass_matrix - (0.5 * step * scaled_alpha) * diffusion"
        ),
        "class": "forward physics (parabolic)",
    },
]


def run_pytest() -> tuple[int, str]:
    environment = dict(os.environ)
    environment.setdefault("PYTHONPATH", ".")
    environment["TORCH_DEVICE_BACKEND_AUTOLOAD"] = "0"
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", TEST_FILE, "-q", "--no-header", "-rf"],
        cwd=REPO, capture_output=True, text=True, env=environment, check=False,
    )
    return proc.returncode, proc.stdout


def failing_tests(output: str) -> list[str]:
    return sorted(set(re.findall(r"^FAILED (\S+)", output, flags=re.MULTILINE)))


def _tail(output: str, lines: int = 2) -> list[str]:
    return [line for line in output.strip().splitlines() if line.strip()][-lines:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="only list the faults")
    args = parser.parse_args()
    if args.dry_run:
        for fault in FAULTS:
            print(f"{fault['id']}: {fault['description']} [{fault['class']}]")
        return 0

    original = DIFFUSION_FILE.read_text()
    record: list[dict] = []
    try:
        for fault in FAULTS:
            assert fault["old"] in original, fault["id"]
            DIFFUSION_FILE.write_text(original.replace(fault["old"], fault["new"], 1))
            code, output = run_pytest()
            record.append({
                "id": fault["id"],
                "fault_class": fault["class"],
                "description": fault["description"],
                "exit_code": code,
                "detected": code != 0,
                "failing_tests": failing_tests(output),
                "red_tail": _tail(output),
            })
            print(f"{fault['id']}: exit={code} failed={len(record[-1]['failing_tests'])}")
            DIFFUSION_FILE.write_text(original)
    finally:
        DIFFUSION_FILE.write_text(original)

    code, output = run_pytest()
    record.append({
        "id": "RESTORED",
        "fault_class": "sanity",
        "description": "unpatched tree: the suite must be green again",
        "exit_code": code,
        "detected": code == 0,
        "failing_tests": failing_tests(output),
        "red_tail": _tail(output),
    })

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "fault_injection.json").write_text(json.dumps(record, indent=2) + "\n")
    lines = [
        "# Fault-injection record -- differentiable inverse problems",
        "",
        "Generated by `python tools/fault_injection_inverse_problem.py`; do not edit by hand.",
        "",
        "| fault | class | patched into | detected | failing assertions |",
        "|---|---|---|---|---|",
    ]
    for entry in record:
        tests = ", ".join(name.split("::")[-1] for name in entry["failing_tests"]) or "(none)"
        lines.append(
            f"| {entry['id']} | {entry['fault_class']} | {entry['description']} | "
            f"{'YES' if entry['detected'] else 'NO'} | {tests} |"
        )
    lines.append("")
    (OUT / "fault_injection.md").write_text("\n".join(lines))

    undetected = [entry["id"] for entry in record[:-1] if not entry["detected"]]
    if undetected or code != 0:
        print("negative control FAILED:", undetected or record[-1]["red_tail"])
        return 1
    print("all faults detected, tree restored and green")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
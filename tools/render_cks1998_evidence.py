"""Render the CKS1998 evidence bundle (manifest + key numbers), zero hand copy.

Reads
    validation/repro_cks1998/artifacts/<profile>/metrics.json
    validation/repro_cks1998/artifacts/<profile>/{*.csv,*.png,summary.md}
    validation/repro_cks1998/benchmark_ref_vs_got.json
and writes
    validation/repro_cks1998/evidence.md

Every digit in the output is read from an artifact file; the tool also records
the sha256 of each artifact so the numbers can be traced to bytes.

Usage
    python -m tools.render_cks1998_evidence                # all present profiles
    python -m tools.render_cks1998_evidence --profiles quick,full
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ROOT = REPO / "validation" / "repro_cks1998"
ART = ROOT / "artifacts"
OUT = ROOT / "evidence.md"

REPRO_CMDS = [
    "OMP_NUM_THREADS=1 python validation/repro_cks1998/repro_cks1998.py --profile quick",
    "OMP_NUM_THREADS=1 python validation/repro_cks1998/repro_cks1998.py --profile full",
    "OMP_NUM_THREADS=1 python validation/repro_cks1998/diagnose_sod_tvd.py",
    "OMP_NUM_THREADS=1 python -m benchmarks.cks1998_benchmark",
    "OMP_NUM_THREADS=1 python -m pytest tests/test_repro_cks1998.py -x -q",
]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def manifest(profile_dir: Path) -> list[dict]:
    rows = []
    for p in sorted(profile_dir.iterdir()):
        if p.is_file():
            rows.append({"file": str(p.relative_to(REPO)), "bytes": p.stat().st_size,
                         "sha256": sha256(p)})
    return rows


def key_numbers(metrics: dict) -> dict:
    sec = metrics["sections"]
    return {
        "A1_order": {k: v["observed_order"] for k, v in sec["A1_smooth"]["by_degree"].items()},
        "A1_gate": {k: v["gate"] for k, v in sec["A1_smooth"]["by_degree"].items()},
        "A2_l1_order": {k: v["l1_order"] for k, v in sec["A2_discontinuous"]["by_degree"].items()},
        "E2_worst_rel_l2": {k: v["worst_rel_l2"] for k, v in sec["E2_sod"]["cases"].items()},
        "E2_gate_case": {k: v["gate_case"] for k, v in sec["E2_sod"]["cases"].items()},
        "E3_overshoot_pct": {k: v["overshoot_pointwise_pct"]
                             for k, v in sec["E3_tvd"]["cases"].items()},
        "verdict": metrics["verdict"],
        "wall_seconds": metrics["wall_seconds"],
        "environment": metrics["environment"],
    }


def render(profiles: list[str]) -> str:
    lines = [
        "# REPRO-DG-CKS1998 — evidence bundle (generated, do not hand-edit)",
        "",
        "Generated by `python -m tools.render_cks1998_evidence` from the run",
        "artifacts below. Every number is read from a file whose sha256 is listed.",
        "",
        "## Reproduction commands",
        "",
        "```bash",
        *REPRO_CMDS,
        "```",
        "",
    ]
    tables = {}
    for prof in profiles:
        pdir = ART / prof
        mp = pdir / "metrics.json"
        if not mp.exists():
            continue
        metrics = json.loads(mp.read_text())
        tables[prof] = key_numbers(metrics)
        lines += [f"## Profile `{prof}` — artifact manifest", "",
                  "| file | bytes | sha256 |", "|---|---:|---|"]
        for row in manifest(pdir):
            lines.append(f"| `{row['file']}` | {row['bytes']} | `{row['sha256']}` |")
        lines += ["", "### Key numbers", "",
                  "| quantity | key | value |", "|---|---|---:|"]
        kn = tables[prof]
        for section in ("A1_order", "A1_gate", "A2_l1_order", "E2_worst_rel_l2",
                        "E2_gate_case", "E3_overshoot_pct"):
            for k, v in kn[section].items():
                val = f"{v:.6g}" if isinstance(v, (int, float)) else str(v)
                if section == "E2_worst_rel_l2" and isinstance(v, float):
                    val = f"{100 * v:.3f} %"
                if section == "E3_overshoot_pct" and isinstance(v, float):
                    val = f"{v:.3f} %"
                lines.append(f"| {section} | {k} | {val} |")
        lines += ["", f"Gate verdict: `{json.dumps(kn['verdict'])}` · "
                      f"wall {kn['wall_seconds']} s · "
                      f"{kn['environment']['python']}/torch {kn['environment']['torch']} "
                      f"on {kn['environment']['cpu']} · "
                      f"loadavg {kn['environment']['host_loadavg']}", ""]

    bm = ROOT / "benchmark_ref_vs_got.json"
    if bm.exists():
        table = json.loads(bm.read_text())
        lines += ["## Reference vs got (from `benchmark_ref_vs_got.json`)", "",
                  f"Profile `{table['profile']}` · rows {table['counts']['total']} "
                  f"(PASS {table['counts']['PASS']} / FAIL {table['counts']['FAIL']} / "
                  f"informative {table['counts']['informative']})", "",
                  "| item | quantity | ref | got | tol | verdict | ref source |",
                  "|---|---|---:|---:|---|---|---|"]
        for r in table["rows"]:
            fmt = lambda v: "" if v is None else (f"{v:.6g}" if isinstance(v, float) else str(v))
            lines.append(f"| {r['item']} | {r['quantity']} | {fmt(r['ref'])} | "
                         f"{fmt(r['got'])} | {r['tolerance']} | {r['verdict']} | "
                         f"{r['ref_source']} |")
        probe = table.get("integration_probe", {})
        lines += ["", f"Integration probe: `probe_pass={probe.get('probe_pass')}`", ""]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--profiles", default="quick,full")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    text = render([p.strip() for p in args.profiles.split(",") if p.strip()])
    Path(args.out).write_text(text)
    print(f"wrote {args.out} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
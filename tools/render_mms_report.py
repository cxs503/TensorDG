"""Render ``docs/reports/tensordg-ns-mms-verification.md`` from the verification JSON.

Every number in the rendered report comes from
``validation/ns_dg_2d/mms_order.json`` (written by
``benchmarks/verify_ns_mms_order.py``); nothing is typed by hand.

Usage::

    PYTHONPATH=. python tools/render_mms_report.py
"""
from __future__ import annotations

import io
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "validation", "ns_dg_2d", "mms_order.json")
TARGET = os.path.join(ROOT, "docs", "reports", "tensordg-ns-mms-verification.md")

FIELD_LABELS = {
    "density": r"$\rho$",
    "momentum_x": r"$\rho u$",
    "momentum_y": r"$\rho v$",
    "energy": r"$E$",
}


def _error_table(study):
    lines = [
        "| degree | cells (per direction) | quadrature | steps | \\|\\|rho\\|\\|_rel | "
        "\\|\\|rho u\\|\\|_rel | \\|\\|rho v\\|\\|_rel | \\|\\|E\\|\\|_rel |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for run in study["runs"]:
        errors = run["errors"]
        cells = run["ncells"]
        cells = cells if isinstance(cells, int) else cells[0]
        lines.append(
            f"| {run['degree']} | {cells} | {run['quadrature']} | {run['steps']} | "
            + " | ".join(f"{100.0 * errors[field]['relative_l2']:.4e}%" for field in
                         ("density", "momentum_x", "momentum_y", "energy"))
            + " |"
        )
    return "\n".join(lines)


def _order_table(study):
    lines = [
        "| degree | field | design order | observed EOC (per mesh pair) | mean EOC | "
        "finest rel. L2 | verdict |",
        "|---:|---|---:|---|---:|---:|---|",
    ]
    for entry in study["summary"]:
        orders = ", ".join(f"{value:.2f}" for value in entry["observed_orders"])
        verdict = "PASS" if entry["within_quarter_order_of_design"] else "SHORT"
        lines.append(
            f"| {entry['degree']} | {FIELD_LABELS[entry['field']]} | {entry['design_order']} | "
            f"{orders} | {entry['mean_observed_order']:.2f} | "
            f"{100.0 * entry['finest_relative_l2']:.4e}% | {verdict} |"
        )
    return "\n".join(lines)


def render():
    with open(SOURCE, encoding="utf-8") as handle:
        study = json.load(handle)
    config = study["config"]
    selfcheck = study["source_selfcheck"]
    activity = study["viscous_activity"]
    control = study["temporal_control"]
    all_ok = study["all_within_quarter_order"]

    verdict = (
        "The coupled convective + viscous operator reproduces the design order "
        "`degree + 1` in the L2 norm for every conserved variable on every degree "
        "tested, so the verification debt recorded in `expand_audit_tensordg.md` "
        "(\"additional Navier--Stokes benchmarks\") is closed for the order of "
        "accuracy question."
        if all_ok else
        "**honest FAIL**: at least one (degree, variable) pair falls short of the "
        "design order by more than a quarter order; the offending cells are marked "
        "SHORT in the table below and are not explained away."
    )

    text = f"""# Manufactured-solution verification of the 2-D compressible Navier--Stokes DG solver

*Generated by `tools/render_mms_report.py` from `validation/ns_dg_2d/mms_order.json`;
reproduce with `PYTHONPATH=. python -m benchmarks.verify_ns_mms_order`.*

## 1. What was missing

`tensordg/ns_dg_2d.py` shipped four verified cases (`mu = kappa = 0` inviscid
limit, viscous Couette flow, pure heat conduction, periodic decaying shear wave)
but never established the **order of accuracy** of the coupled convective +
viscous operator: the shear-wave case compares profiles on two coarse meshes at a
single degree, which cannot distinguish design order from a plausible-looking
profile.  `expand_audit_tensordg.md` §3.3 and the README list "additional
Euler/Navier--Stokes benchmarks" as future work; this report pays that debt for
the order-of-accuracy question.

## 2. Method

1. `tools/derive_ns_mms_source.py` derives, with sympy and no hand
   differentiation, the conserved-variable source
   `S = dU/dt + div F_inv - div F_visc` for the manufactured state
   `rho = 1 + 0.20 sin(2 pi x + 0.40 t) cos(2 pi y - 0.30 t)`,
   `u = 0.5 + 0.10 sin(2 pi y + 0.20 t) cos(2 pi x)`,
   `v = -0.4 + 0.10 sin(2 pi x - 0.10 t) cos(2 pi y + 0.25 t)`,
   `p = 1 + 0.25 cos(2 pi x + 0.15 t) sin(2 pi y + 0.20 t)`
   (1-periodic in both directions, smooth, O(10 %) amplitude).  The generated
   module `tensordg/mms_ns_2d.py` is plain torch, so neither the driver nor the
   test suite needs sympy at run time.
2. `tensordg/ns_dg_2d.py` gained an optional volumetric `source` hook
   (`source(x, y, time) -> (S_rho, S_rhou, S_rhov, S_E)`), projected onto the
   modal basis with the exact tensor-product mass matrix and evaluated at the
   SSP-RK3 stage times; `source=None` reproduces the previous behaviour
   bit-for-bit (the existing NS tests still pass unchanged).
3. The manufactured problem is integrated from `t = 0` to `T = {config['final_time']}`
   with `mu = {config['mu']}`, `Pr = {config['prandtl']}` (`kappa = {config['kappa']:.6f}`),
   `cfl = {config['cfl']}`, `cfl_viscous = {config['cfl_viscous']}` and quadrature
   order `2 degree + 3`; the L2 error of every conserved variable against the
   analytic state is measured with the same Gauss--Legendre quadrature.

### 2.1 Tool verification (protection against a wrong source)

The generated source was cross-checked against a **central-difference** evaluation
of the same PDE (a deliberately independent code path that rebuilds the flux
divergences from the definitions in the module docstring):

| quantity | value |
|---|---:|
| samples | {selfcheck['points']} |
| time | {selfcheck['time']} |
| max abs source | {selfcheck['max_abs_source']:.6f} |
| max abs difference | {selfcheck['max_abs_difference']:.3e} |
| relative difference | {selfcheck['relative_difference']:.3e} |
| verdict | {'PASS' if selfcheck['pass'] else 'FAIL'} |

A sign or constitutive-law mistake in the derivation would give an O(1)
discrepancy here instead of {selfcheck['relative_difference']:.1e}, so the
convergence study below measures the solver and not the source.

### 2.2 The viscous operator is genuinely exercised

| quantity | value |
|---|---:|
| max abs viscous source | {activity['max_abs_viscous_source']:.4f} |
| max abs inviscid source | {activity['max_abs_inviscid_source']:.4f} |
| viscous / inviscid | {activity['ratio']:.3f} |

### 2.3 Time-integration error control

One case was re-run with all CFL numbers halved ({control['degree']}, {control['ncells']}
cells): {control['reference_steps']} -> {control['refined_steps']} steps, maximum relative
change of the measured L2 errors {100.0 * control['max_relative_change']:.3f}%
(threshold 2 %).  The observed orders below are therefore spatial, not temporal.

## 3. Results

Meshes: {config['meshes']} for degrees {config['degrees']}, {config['meshes_high_degree']} for degree 3.

{_error_table(study)}

Observed order of accuracy (`EOC = log(e_coarse / e_fine) / log(h_coarse / h_fine)`):

{_order_table(study)}

**Verdict.** {verdict}

![manufactured-solution order verification](../figures/ns_dg_2d_mms_order.png)

*Left: L2 error of the density versus mesh size with the reference slope
`degree + 1`.  Right: cell-wise L2 density error on the finest mesh of the
{study['config']['degrees'][-1]} degree run.*

## 4. Things worth knowing

- The `source` hook is a genuine API addition, not test scaffolding: body
  forces, gravity or a chemical/relaxation term enter the DG residual exactly
  this way, and the projection uses the modal mass matrix
  `(2i+1)(2j+1)/4`, which is why a constant source lands exactly in the
  cell-average mode.
- The BR1/SIPG penalty term is invisible in this test in the sense that its
  contribution to the *residual of a smooth state* shrinks with the jumps; the
  penalty's stability role is exercised by the shear-wave and Couette cases
  instead.  Order-of-accuracy verification and stability verification are
  complementary, not interchangeable.
- Explicit diffusion makes the run cost grow like `h^-3` (steps `~ h^-2` times
  cells `~ h^-2`), which is why the ladder stops at 32 cells per direction at
  degree 2 within this budget.  Nothing in the method prevents a finer ladder.
- The manufactured amplitudes are O(10 %) around a state with `|u|, |v| <= 0.6`,
  `c ~ 1.2`; the positivity filter never triggered in these runs (no
  `FloatingPointError` and no limiter active), so the measured order is the
  order of the unmodified DG operator.

## 5. Error judgement against the benchmark

The verification question here is the **order of accuracy**, so the benchmark is
the design order `degree + 1` itself, not a physical reference value:

| degree | design order | mean observed order over all variables | within 0.25 order |
|---:|---:|---:|---|
"""
    for degree in sorted({entry["degree"] for entry in study["summary"]}):
        entries = [entry for entry in study["summary"] if entry["degree"] == degree]
        mean = sum(entry["mean_observed_order"] for entry in entries) / len(entries)
        ok = all(entry["within_quarter_order_of_design"] for entry in entries)
        text += f"| {degree} | {degree + 1} | {mean:.2f} | {'yes' if ok else 'no'} |\n"

    text += f"""
**Is the error below the 3 % acceptance threshold?** Not applicable as stated:
this is a convergence-order verification, not a physical-fidelity comparison, so
the 3 % criterion has no meaning for a manufactured solution that can be made
arbitrarily small by refining the mesh.  What is asserted instead, and what the
project treats as the equivalent acceptance criterion here, is *observed order
within a quarter order of design* for every conserved variable — the outcome is
{'PASS for every (degree, variable) pair' if all_ok else 'FAIL for at least one pair (see SHORT rows)'}.

For reference, the finest-mesh relative L2 errors in the table above
({100.0 * min(entry['finest_relative_l2'] for entry in study['summary']):.2e}% at best,
{100.0 * max(entry['finest_relative_l2'] for entry in study['summary']):.2e}% at worst)
are far below 3 % simply because the meshes are resolved; that number is a
sanity check, not the verification criterion.
"""

    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    io.open(TARGET, "w", encoding="utf-8").write(text)
    print(f"wrote {TARGET} ({len(text)} bytes)")
    return TARGET


if __name__ == "__main__":
    render()